/**
 * Console budget (hds#959): every console.warn / console.error a docs demo
 * prints is reduced to a stable code, and a code that is not in the committed
 * allowlist fails the test. An allowed code names its issue and the upgrade
 * ledger step that tells consumers about it, since they see the same warning.
 *
 * The allowlist is generated, never hand-edited: rerun the gate with
 * HDS_UPDATE_CONSOLE_ALLOWLIST=1 and it rewrites the file from what the demos
 * printed, sorted, keeping each entry's issue and upgrade fields.
 */

export type ConsoleLevel = 'warn' | 'error';

export interface AllowlistEntry {
  code: string;
  demos: string[];
  /** hirobius/hds#N: the issue that fixes or explains the warning. */
  issue: string;
  /** An upgrade/pending note name, or a step id in upgrade/releases/*.json. */
  upgrade: string;
}

export interface Allowlist {
  $comment: string;
  codes: AllowlistEntry[];
}

/** code → the demos that printed it */
export type Seen = Map<string, Set<string>>;

export const ALLOWLIST_COMMENT =
  'Generated by tests/docs-site/console-budget.test.tsx (HDS_UPDATE_CONSOLE_ALLOWLIST=1); do not edit codes or demos by hand. Fill issue (hirobius/hds#N) and upgrade (an upgrade/pending note or a release step id) for each entry.';

const ISSUE = /^hirobius\/hds#\d+$/;

/**
 * One console call → a stable code. Fills React's %s slots from the later
 * arguments (so two different prop-type warnings stay two codes), keeps the
 * first line (the component stack falls away) and blanks quoted values and
 * numbers, so the same warning from two demos, or two runs, is one code.
 */
export function consoleCode(level: ConsoleLevel, args: unknown[]): string {
  const [first, ...rest] = args;
  let raw = first instanceof Error ? first.message : String(first);
  if (typeof first === 'string') {
    let i = 0;
    raw = raw.replace(/%[sdifoOc]/g, () => (i < rest.length ? String(rest[i++]) : '*'));
  }
  const msg = (raw.split('\n')[0] ?? '')
    // A quote with no space inside is a value; an apostrophe in prose is not.
    .replace(/(["'`])[^\s"'`]*\1/g, '*')
    .replace(/"[^"]*"|`[^`]*`/g, '*')
    .replace(/\d+(?:\.\d+)?/g, 'N')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 160);
  return `${level}: ${msg}`;
}

export function record(seen: Seen, demo: string, level: ConsoleLevel, args: unknown[]): void {
  const code = consoleCode(level, args);
  const demos = seen.get(code) ?? new Set<string>();
  demos.add(demo);
  seen.set(code, demos);
}

/** The allowlist the demos call for: what they printed, sorted, with the old issue/upgrade kept. */
export function renderAllowlist(seen: Seen, previous?: Allowlist): Allowlist {
  const old = new Map((previous?.codes ?? []).map((e) => [e.code, e]));
  const codes = [...seen.keys()].sort().map((code) => ({
    code,
    demos: [...(seen.get(code) ?? [])].sort(),
    issue: old.get(code)?.issue ?? '',
    upgrade: old.get(code)?.upgrade ?? '',
  }));
  return { $comment: ALLOWLIST_COMMENT, codes };
}

/** Everything wrong with the budget, as lines to print; empty means green. */
export function budgetProblems(
  seen: Seen,
  allowlist: Allowlist,
  ledgerHas: (ref: string) => boolean,
): string[] {
  const problems: string[] = [];
  const listed = new Set(allowlist.codes.map((e) => e.code));
  for (const [code, demos] of [...seen].sort(([a], [b]) => a.localeCompare(b))) {
    if (!listed.has(code)) {
      problems.push(`new console code (${[...demos].sort().join(', ')}): ${code}`);
    }
  }
  for (const entry of allowlist.codes) {
    if (!seen.has(entry.code)) problems.push(`allowlisted code no longer printed: ${entry.code}`);
    if (!ISSUE.test(entry.issue)) problems.push(`no issue (hirobius/hds#N) for: ${entry.code}`);
    if (!entry.upgrade || !ledgerHas(entry.upgrade)) {
      problems.push(`no upgrade ledger step "${entry.upgrade}" for: ${entry.code}`);
    }
  }
  if (problems.length === 0) {
    const want = JSON.stringify(renderAllowlist(seen, allowlist));
    if (JSON.stringify(allowlist) !== want) problems.push('allowlist is not in generated form');
  }
  return problems;
}
