/** The fields of a Fumadocs page this module reads. */
export interface LandingSourcePage {
  slugs: string[];
  url: string;
  data: { title: string; description?: string };
}

export interface SectionLanding {
  /** Top-level folder slug, e.g. "components". */
  section: string;
  /** Sentence-case title from the folder name ("getting-around" -> "Getting around"). */
  title: string;
  pages: { title: string; url: string; description?: string }[];
}

const titleFor = (slug: string) => {
  const words = slug.replace(/-/g, ' ');
  return words.charAt(0).toUpperCase() + words.slice(1);
};

/**
 * Every top-level section of /docs that has pages but no index page of its own,
 * so the catch-all route can render a landing there instead of a 404.
 * components/ and patterns/ are regenerated by `pnpm docs:components`, so their
 * roots can only ever come from here; any section that later gains a hand-written
 * index.mdx drops out on its own.
 */
export function sectionLandings(pages: LandingSourcePage[]): SectionLanding[] {
  const indexed = new Set(pages.filter((p) => p.slugs.length === 1).map((p) => p.slugs[0]));
  const bySection = new Map<string, SectionLanding['pages']>();
  for (const p of pages) {
    const [section] = p.slugs;
    if (p.slugs.length < 2 || !section || indexed.has(section)) continue;
    const list = bySection.get(section) ?? [];
    list.push({ title: p.data.title, url: p.url, description: p.data.description });
    bySection.set(section, list);
  }
  return [...bySection.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([section, list]) => ({
      section,
      title: titleFor(section),
      pages: list.sort((a, b) => a.title.localeCompare(b.title)),
    }));
}
