#!/usr/bin/env node
/** @internal — not part of @hirobius/design-system public API surface. */
/**
 * figma-inventory.mjs — write or read `figma/inventory.json`.
 *
 *   pnpm figma:inventory                      print coverage from the committed inventory
 *   pnpm figma:inventory --json               the same, as JSON
 *   FIGMA_ACCESS_TOKEN=<token> pnpm figma:inventory --fetch
 *                                             re-read the document and rewrite the inventory
 *
 * The committed inventory is what makes the Figma library legible to an agent
 * with no Figma access at all: page names, component-set ids, variant counts.
 * `--fetch` is the only path that talks to Figma, and it is one REST call.
 *
 * Why REST and not the MCP server: `list_file_components_for_code_connect`
 * needs an Organization plan, and `get_metadata` with no node id reports the
 * loaded page rather than the document, so it answers "Cover" no matter how
 * many pages exist. `GET /v1/files/:key` is not plan-gated. See ADR-026.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseDocument, coverage, fetchFile } from './lib/figma-inventory.mjs';
import { figmaToken, figmaTokenSource } from './lib/figma-token.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const INVENTORY = path.join(ROOT, 'figma/inventory.json');
const LINKS = path.join(ROOT, 'figma/links.json');
const MANIFEST = path.join(ROOT, 'public/hds-manifest.json');

const args = process.argv.slice(2);
const asJson = args.includes('--json');

function readJson(file, what) {
  try {
    return JSON.parse(readFileSync(file, 'utf8'));
  } catch (error) {
    throw new Error(`Could not read ${what} (${path.relative(ROOT, file)}): ${error.message}`);
  }
}

async function refetch() {
  const links = readJson(LINKS, 'the Figma links config');
  const fileKey = links.libraryFileKey;
  if (!fileKey) {
    console.error(
      '✗ figma:inventory — libraryFileKey is not set in figma/links.json, so there is no file to read.',
    );
    process.exit(1);
  }

  const source = figmaTokenSource();
  if (source) console.log(`  using the Figma token from ${source}`);
  const file = await fetchFile({ fileKey, token: figmaToken() });
  const parsed = parseDocument(file, fileKey);

  const inventory = {
    $comment:
      'Generated by `pnpm figma:inventory --fetch`. The published Figma library, as data: every page, every component set, every variant count. Committed so an agent can traverse the design system without Figma access. Regenerate rather than hand-edit — scripts/check-figma-coverage.mjs reads this to find components that exist in Figma but are unmapped in code.',
    generatedAt: new Date().toISOString(),
    source: 'rest',
    complete: true,
    ...parsed,
  };

  writeFileSync(INVENTORY, `${JSON.stringify(inventory, null, 2)}\n`, 'utf8');
  const assets = inventory.pages.reduce((n, page) => n + page.assets.length, 0);
  console.log(
    `✓ figma:inventory — wrote figma/inventory.json: ${inventory.pages.length} page(s), ${assets} asset(s)`,
  );
}

function report() {
  const inventory = readJson(INVENTORY, 'the Figma inventory');
  const manifest = readJson(MANIFEST, 'the manifest');
  const result = coverage(inventory, manifest);

  if (asJson) {
    console.log(JSON.stringify({ ...result, complete: inventory.complete !== false }, null, 2));
    return;
  }

  console.log(
    `figma:inventory — ${result.mapped} of ${result.total} Figma asset(s) mapped in code` +
      (inventory.complete === false ? ' (inventory INCOMPLETE — see below)' : ''),
  );
  for (const page of inventory.pages ?? []) {
    if (!page.assets?.length) continue;
    console.log(`  ${page.name} (${page.id})`);
    for (const asset of page.assets) {
      console.log(`    ${asset.id.padEnd(10)} ${asset.name} · ${asset.variantCount} variant(s)`);
    }
  }
  if (inventory.complete === false) {
    console.log(
      `\n  Inventory is incomplete: ${inventory.incompleteReason ?? 'no reason recorded'}`,
    );
  }
}

try {
  if (args.includes('--fetch')) await refetch();
  else report();
} catch (error) {
  console.error(`✗ figma:inventory — ${error.message}`);
  process.exit(1);
}
