#!/usr/bin/env node
/** @internal — not part of @hirobius/design-system public API surface. */
/**
 * generate-staging-inventory — render the Figma staging promotion checklist.
 *
 * This file exists because the first version of that checklist was a
 * hand-typed markdown table: 39 rows of component name, variant count and
 * staging node id, asserting current facts about a file that changes, with
 * nothing reading or validating it. Staging node ids explicitly do NOT survive
 * promotion, so the table was guaranteed to go wrong — the same shape as the
 * three stale generated artifacts this repo already carries.
 *
 * The data now lives in figma/staging-inventory.json and the markdown is
 * rendered from it. --check fails when the two disagree, so the generated file
 * cannot be edited by hand and quietly kept.
 *
 *   pnpm figma:staging-inventory
 *   pnpm figma:staging-inventory --check
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DATA = path.join(ROOT, 'figma/staging-inventory.json');
const OUT = path.join(ROOT, 'figma/STAGING-INVENTORY.md');
const CHECK = process.argv.includes('--check');

if (!existsSync(DATA)) {
  console.error('✗ generate-staging-inventory — figma/staging-inventory.json is missing');
  process.exit(1);
}
const data = JSON.parse(readFileSync(DATA, 'utf8'));
const links = JSON.parse(readFileSync(path.join(ROOT, 'figma/links.json'), 'utf8'));
const fileKey = data.fileKey ?? links.stagingFileKey;

const entries = Object.entries(data.components).sort(([a], [b]) => a.localeCompare(b));
// Adrian asked for "links to them in figma", so the name IS the link — a node
// id in code font is a thing you have to assemble a URL from by hand.
const nodeUrl = (node) => `https://www.figma.com/design/${fileKey}/?node-id=${node}`;

const row = ([name, c]) =>
  `| [${name}](${nodeUrl(c.node)}) | ${c.kind} | ${c.variants ?? '—'} | \`${c.node}\` |`;

const earlier = Object.entries(data.drawnEarlier ?? {})
  .map(([name, c]) => `**[${name}](${nodeUrl(c.node)})** (${c.variants} ${c.kind})`)
  .join(' and ');

const md = `<!-- GENERATED by scripts/generate-staging-inventory.mjs from
     figma/staging-inventory.json. Do not hand-edit: pnpm figma:staging-inventory --check
     fails when this file and that data disagree. -->

# Staging inventory — components drawn by an agent, awaiting promotion

Every component below lives ONLY in the staging file \`${fileKey}\`. Per ADR-026
the published library is read-only to agents, so promotion is a manual step
Adrian performs.

**Do not add an \`@figma\` JSDoc tag for anything on this list yet.** Staging node
ids do not survive promotion — \`figma/COMPONENT-DRAWING-RECIPE.md\` §Promotion is
the sequence: promote, take the NEW library node id, add the tag, then
\`pnpm manifest:generate\`.


## Why the sync gate still reports these as missing

\`check-sync-map\` counts a library component as linked when it carries an
\`@figma\` tag or a \`figma/mapping-overrides.json\` entry. The recipe forbids
tagging a component that lives only in staging. So **staging work is
structurally invisible to the gate**, and Figma coverage reads 47/88 until
promotion — not because the components are absent, but because the only record
the gate can read is the one the recipe says not to write yet. That is a gap in
the measurement, not drift.

## Drawn ${data.drawnOn} (${entries.length} components)

| Component | Kind | Variants | Node |
|---|---|---|---|
${entries.map(row).join('\n')}

Drawn earlier, same status: ${earlier}.

## Verification gap, stated plainly

Nothing here can currently self-verify. Confirming these node ids against the
live staging file needs the Figma REST token, which is what \`pnpm figma:inventory\`
uses and which is not working. Until it is, treat this as a dated record of what
one session drew, not as proof of the file's present contents — which is why the
node ids live in JSON a script can check rather than in prose nobody can.
`;

if (CHECK) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== md) {
    console.error('✗ figma/STAGING-INVENTORY.md is out of date with figma/staging-inventory.json');
    console.error('  fix: pnpm figma:staging-inventory');
    process.exit(1);
  }
  console.log(`✓ staging inventory matches its data (${entries.length} components)`);
} else {
  writeFileSync(OUT, md);
  console.log(`✓ ${path.relative(ROOT, OUT)} — ${entries.length} components`);
}
