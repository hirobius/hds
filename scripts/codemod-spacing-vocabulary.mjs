#!/usr/bin/env node
/** @internal — not part of @hirobius/design-system public API surface. */
/**
 * codemod-spacing-vocabulary.mjs
 *
 * hds#206 remaining work — moves hds's OWN internal spacing-token references
 * off the deprecated `semantic.space.{component,layout}.*` aliases and onto
 * the canonical t-shirt scale (`semantic.space.scale.{xs,sm,md,lg,xl}`, slice
 * 1 of hds#206, shipped in #297).
 *
 * Scope (deliberately narrow — see hds#206 comment history):
 *   - This rewrites internal token REFERENCES (CSS `var(--semantic-space-…)`
 *     strings, and `hds.semantic.space.…` / bare `semantic.space.…` dotted
 *     paths) inside hds's own src/ — not the public `gap`/`padding` prop
 *     VALUES (`gap="tight"`, `padding="component"`, …) that Stack/Card/Grid/
 *     etc. accept. Those remain a distinct, separate consumer-facing surface;
 *     migrating external consumers (ops, portal-kit) off them is tracked
 *     separately in the issue. The deprecated aliases in
 *     `hirobius.tokens.json` are NOT removed by this script and the
 *     `check-spacing-vocabulary` gate stays in warn mode — both explicitly
 *     out of scope for this slice.
 *
 * Deprecated → canonical mapping (identical resolved px value each side —
 * this is a pure rename, not a value change):
 *   semantic.space.component.gap      (8px)  → semantic.space.scale.xs
 *   semantic.space.layout.tight       (16px) → semantic.space.scale.sm
 *   semantic.space.layout.normal      (24px) → semantic.space.scale.md
 *   semantic.space.layout.inset       (32px) → semantic.space.scale.lg
 *   semantic.space.layout.spacious    (48px) → semantic.space.scale.xl
 *
 *   semantic.space.component.padding (24px) → semantic.space.surface.padding
 *   semantic.space.layout.gutter      (24px) → semantic.space.region.gutter
 *
 * The last two are not scale steps: tenants.css (per tenant/density) and
 * theme.css (responsive 32px/16px) override them at runtime, so they rename
 * to overridable roles whose default is scale.md and whose overrides are
 * themselves scale steps (hds#206 slice 3). The deprecated names stay as
 * `$deprecated` aliases, re-anchored inside each tenant block, so a consumer
 * that has not run this codemod keeps the same computed values.
 *
 * What it does NOT touch (by design):
 *   - Generated build output (`generated-*.ts`, `generated-token-vars.d.ts`,
 *     `tokens.css`, `tokens.generated.css`, `tenants.css`) — regenerated by
 *     `pnpm tokens` from `hirobius.tokens.json`; hand-editing them is banned
 *     by CLAUDE.md.
 *   - Generated audit/report snapshots (`token-usage-map.json`,
 *     `token-audit-report.json`, `component-api.json`) — these describe
 *     usage, they aren't usage.
 *   - `--semantic-space-layout-gap` / `--semantic-layout-*` — a distinct,
 *     unrelated responsive-shell token (not one of the 7 deprecated aliases
 *     from hds#206) that happens to share a substring with `layout-gutter`;
 *     the replacement table below matches full token names only, so it is
 *     never touched.
 *   - `--semantic-space-layout-gutter`'s own CSS *declaration* in
 *     `theme.css` (a responsive override of the raw custom property, not a
 *     `var()` consumption site) — only `var(--semantic-space-layout-gutter)`
 *     read sites are rewritten.
 *
 * Idempotent: canonical strings never appear on the left-hand side of any
 * rule, so a second run finds zero matches.
 *
 * Run:      node scripts/codemod-spacing-vocabulary.mjs           (apply)
 *           node scripts/codemod-spacing-vocabulary.mjs --check   (dry run; exits 1 if it would change anything)
 */

import { readFileSync, writeFileSync, readdirSync, statSync } from 'fs';
import { join, dirname, extname, relative, resolve } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SRC = join(ROOT, 'src');

// Ordered list of [search, replace] literal-substring rules. Order does not
// matter — none of the search strings are substrings of one another, and no
// replacement string ever becomes a new match for a later rule.
export const REPLACEMENTS = [
  // CSS custom-property consumption sites: `var(--semantic-space-…)`.
  ['var(--semantic-space-component-gap)', 'var(--semantic-space-scale-xs)'],
  ['var(--semantic-space-layout-tight)', 'var(--semantic-space-scale-sm)'],
  ['var(--semantic-space-layout-normal)', 'var(--semantic-space-scale-md)'],
  ['var(--semantic-space-layout-inset)', 'var(--semantic-space-scale-lg)'],
  ['var(--semantic-space-layout-spacious)', 'var(--semantic-space-scale-xl)'],
  // The two runtime-overridden tokens (hds#206 slice 3) rename to their
  // overridable role names, NOT to scale.md: tenants.css (brand/density) and
  // theme.css (responsive) override these roles, and a scale step would drop
  // those overrides.
  ['var(--semantic-space-component-padding)', 'var(--semantic-space-surface-padding)'],
  ['var(--semantic-space-layout-gutter)', 'var(--semantic-space-region-gutter)'],
  // JS/TS dotted token-bridge paths (`hds.semantic.space.…` and bare
  // `semantic.space.…` string labels, e.g. in Storybook demo args). A bare
  // match also fixes the `hds.`-prefixed form as a side effect, since it's
  // a literal substring of it — no separate rule needed for that case.
  ['semantic.space.component.gap', 'semantic.space.scale.xs'],
  ['semantic.space.component.padding', 'semantic.space.surface.padding'],
  ['semantic.space.layout.gutter', 'semantic.space.region.gutter'],
];

// Files/paths (repo-relative, forward-slash) this codemod never touches:
// generated build output and generated audit/report snapshots.
const SKIP_FILES = new Set([
  'src/app/design-system/generated-token-descriptions.ts',
  'src/app/design-system/generated-token-refs.ts',
  'src/app/design-system/generated-token-values.ts',
  'src/app/design-system/generated-token-vars.d.ts',
  'src/app/design-system/generated-tokens.ts',
  'src/app/design-system/token-usage-map.json',
  'src/app/data/token-audit-report.json',
  'src/app/data/component-api.json',
  'src/styles/tokens.css',
  'src/styles/tokens.generated.css',
  'src/styles/tenants.css',
]);

const EXTENSIONS = new Set(['.ts', '.tsx', '.css']);
const SKIP_DIRS = new Set(['node_modules', '.git', 'dist']);

function collectFiles(dir, results = []) {
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    const stat = statSync(full);
    if (stat.isDirectory()) {
      collectFiles(full, results);
      continue;
    }
    if (EXTENSIONS.has(extname(entry))) results.push(full);
  }
  return results;
}

/**
 * Applies every replacement rule to `text` once.
 * @param {string} text
 * @returns {{ text: string, count: number }}
 */
export function applyReplacements(text) {
  let out = text;
  let count = 0;
  for (const [search, replace] of REPLACEMENTS) {
    let idx = out.indexOf(search);
    while (idx !== -1) {
      out = out.slice(0, idx) + replace + out.slice(idx + search.length);
      count += 1;
      idx = out.indexOf(search, idx + replace.length);
    }
  }
  return { text: out, count };
}

function main() {
  const checkOnly = process.argv.includes('--check');
  const files = collectFiles(SRC);

  const changed = [];
  for (const file of files) {
    const rel = relative(ROOT, file).replace(/\\/g, '/');
    if (SKIP_FILES.has(rel)) continue;

    const original = readFileSync(file, 'utf-8');
    const { text, count } = applyReplacements(original);
    if (count === 0) continue;

    changed.push({ file: rel, count });
    if (!checkOnly) writeFileSync(file, text, 'utf-8');
  }

  if (changed.length === 0) {
    console.log('[ok] codemod-spacing-vocabulary — no deprecated spacing-token references found');
    process.exit(0);
  }

  const verb = checkOnly ? 'would rewrite' : 'rewrote';
  console.log(
    `[codemod-spacing-vocabulary] ${verb} ${changed.reduce((n, c) => n + c.count, 0)} reference(s) across ${changed.length} file(s):`,
  );
  for (const c of changed) {
    console.log(`  ${c.file} (${c.count})`);
  }

  if (checkOnly) process.exit(1);
  process.exit(0);
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  main();
}
