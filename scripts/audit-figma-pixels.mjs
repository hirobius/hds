/**
 * scripts/audit-figma-pixels.mjs — code render vs Figma render, per variant (hds#1147).
 *
 * Piloted on the parity components (check-figma-components: Button, IconButton).
 * For each variant of the Figma set (Variant x Size x State) it renders the same
 * <Button> from the built library (dist/) in Chromium, crops the variant out of a
 * committed Figma screenshot of the set, and compares the two with pixelmatch.
 *
 * Inputs (committed, refreshed by hand when Figma changes):
 *   figma/pixels/<Name>.geometry.json  variant boxes in the set, from the generated
 *                                      read-only use_figma script (--emit-script, --ingest)
 *   figma/pixels/<Name>.png            get_screenshot of the set (its scale is read from the
 *                                      PNG width; get_screenshot gives 1x)
 *
 * Usage:
 *   node scripts/audit-figma-pixels.mjs                 report, exit 0
 *   node scripts/audit-figma-pixels.mjs --json          the rows as JSON
 *   node scripts/audit-figma-pixels.mjs --out <dir>     also write code, figma and diff PNGs
 *   node scripts/audit-figma-pixels.mjs --emit-script   write figma/push/use-figma/pixel-geometry.js
 *   node scripts/audit-figma-pixels.mjs --ingest <f>    write figma/pixels/<Name>.geometry.json
 *
 * Needs `pnpm build:lib` first (dist/). Report only: it never fails. Never writes to Figma.
 * No shebang: vitest injects an import above the file's dynamic imports, before line 1.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { PNG } from 'pngjs';
import pixelmatch from 'pixelmatch';
import { COMPONENTS, readJson, cliArgs, writeUseFigmaScript } from './check-figma-components.mjs';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const PIXELS = 'figma/pixels';
/** pixelmatch colour threshold; anti-aliased pixels are not counted. */
const THRESHOLD = 0.1;

/** `Variant=primary, Size=md, State=hover` -> { variant, size, state }. */
export function parseVariant(name) {
  const o = {};
  for (const part of name.split(',')) {
    const [k, v] = part.split('=').map((s) => s.trim());
    o[k.toLowerCase()] = v;
  }
  return o;
}

/** Cut a w x h box at (x, y) out of a PNG. Pixels outside the source are transparent. */
export function crop(png, x, y, w, h) {
  const out = new PNG({ width: w, height: h });
  for (let j = 0; j < h; j++)
    for (let i = 0; i < w; i++) {
      const sx = x + i;
      const sy = y + j;
      const d = (j * w + i) * 4;
      if (sx < 0 || sy < 0 || sx >= png.width || sy >= png.height) continue;
      const s = (sy * png.width + sx) * 4;
      for (let c = 0; c < 4; c++) out.data[d + c] = png.data[s + c];
    }
  return out;
}

/** Compare two renders. Sizes differ -> both are padded to the larger box. */
export function compare(a, b) {
  const w = Math.max(a.width, b.width);
  const h = Math.max(a.height, b.height);
  const pa = crop(a, 0, 0, w, h);
  const pb = crop(b, 0, 0, w, h);
  const diff = new PNG({ width: w, height: h });
  const n = pixelmatch(pa.data, pb.data, diff.data, w, h, { threshold: THRESHOLD });
  return {
    sizeCode: [a.width, a.height],
    sizeFigma: [b.width, b.height],
    diffPixels: n,
    diffPercent: Math.round((n / (w * h)) * 10000) / 100,
    diff,
  };
}

/** The font the Button label uses; a render without it measures a fallback (hds#1295). */
export const BRAND_FONT = '510 16px "Sora"';

/** Abort the code render when the brand font did not load. */
export function requireBrandFont(loaded) {
  if (!loaded)
    throw new Error(
      `${BRAND_FONT} did not load in the code render; check the url rewrite of dist/fonts.css (rebaseFontUrls). Aborting: a fallback font makes every label measure wrong.`,
    );
}

/** Point dist/fonts.css's relative ./fonts/ urls (quoted or not) at `dir`, so a file page loads them. */
export function rebaseFontUrls(css, dir) {
  return css.replace(/url\((['"]?)\.\/fonts\//g, (_, q) => `url(${q}${dir}/`);
}

export function buildGeometryScript({ root = REPO } = {}) {
  const links = readJson(join(root, 'figma/links.json'));
  const sets = Object.entries(COMPONENTS).map(([name, c]) => [name, c.nodeId]);
  return `// HDS pixel-compare geometry. Generated by scripts/audit-figma-pixels.mjs --emit-script; run it unmodified.
// Reads only. Save the returned JSON, then: node scripts/audit-figma-pixels.mjs --ingest <file>
if (figma.fileKey !== '${links.libraryFileKey}') throw new Error('Refused: this is not the HDS library. Nothing was read.');
const SETS = ${JSON.stringify(sets)};
const out = {};
for (const [name, id] of SETS) {
  const set = await figma.getNodeByIdAsync(id);
  if (!set || set.type !== 'COMPONENT_SET') throw new Error(id + ' is not a component set.');
  const b = set.absoluteBoundingBox;
  const r = set.absoluteRenderBounds || b;
  out[name] = {
    nodeId: id,
    // get_screenshot renders the render bounds (effects included); offsets are from its top-left.
    render: { x: r.x, y: r.y, width: r.width, height: r.height },
    box: { x: b.x, y: b.y, width: b.width, height: b.height },
    variants: set.children.map((v) => ({ name: v.name, x: v.absoluteBoundingBox.x - r.x, y: v.absoluteBoundingBox.y - r.y, width: v.width, height: v.height })),
  };
}
return out;
`;
}

function codeProps(component, v) {
  const p = {
    variant: v.variant,
    size: v.size,
    label: 'Button',
    disabled: v.state === 'disabled',
    // The wipe hover fill is drawn by a JS listener; a static render shows the same
    // end fill in place.
    hoverEffect: 'none',
  };
  if (component === 'IconButton') Object.assign(p, { iconOnly: true });
  return p;
}

async function renderCode(
  component,
  variants,
  { root = REPO, scale = 1, backdrop = 'transparent' } = {},
) {
  const React = await import('react');
  const { renderToStaticMarkup } = await import('react-dom/server');
  const lib = await import(
    /* @vite-ignore */ pathToFileURL(join(root, 'dist/hirobius-ui.js')).href
  );
  const { Plus } = await import('lucide-react');
  const css = rebaseFontUrls(
    ['fonts.css', 'styles.css'].map((f) => readFileSync(join(root, 'dist', f), 'utf8')).join('\n'),
    pathToFileURL(join(root, 'dist/fonts')).href,
  );
  const { chromium } = await import('playwright');
  // CHROMIUM_PATH: a browser outside Playwright's own cache (e.g. a pre-installed one).
  const browser = await chromium.launch(
    process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {},
  );
  const page = await browser.newPage({ deviceScaleFactor: scale });
  const htmlPath = join(mkdtempSync(join(tmpdir(), 'hds-pixels-')), 'variant.html');
  const out = [];
  try {
    for (const v of variants) {
      const props = codeProps(component, v);
      if (component === 'IconButton') props.iconLeft = React.createElement(Plus);
      const html = renderToStaticMarkup(React.createElement(lib.Button, props));
      // A file page, so the file:// fonts load. The [data-hds] scope gives the library's
      // own reset; the backdrop is the Figma canvas colour.
      writeFileSync(
        htmlPath,
        `<!doctype html><html class="light"><head><style>${css}</style>` +
          `<style>*,*::before,*::after{transition:none!important;animation:none!important}` +
          `body{margin:0;padding:24px;background:${backdrop}}</style></head>` +
          `<body data-hds><div id="c" style="display:inline-block">${html}</div></body></html>`,
      );
      await page.goto(pathToFileURL(htmlPath).href);
      await page.evaluate(() => document.fonts.ready);
      // Not document.fonts.check(): it can return true for a face in the 'error' state and when
      // no face matches the family, so it would not catch the #1295 fallback. load() returns
      // the matching faces; each must have status 'loaded'.
      requireBrandFont(
        await page.evaluate(async (f) => {
          try {
            const faces = await document.fonts.load(f);
            return faces.length > 0 && faces.every((x) => x.status === 'loaded');
          } catch {
            return false;
          }
        }, BRAND_FONT),
      );
      const btn = page.locator('#c > *').first();
      await page.mouse.move(0, 0);
      // The rest box, like Figma's variant frame: hover and press move the face (translate)
      // inside it (hds#1296), so the clip must not follow the face.
      const box = await btn.boundingBox();
      if (v.state === 'hover' || v.state === 'pressed') await btn.hover();
      if (v.state === 'pressed') await page.mouse.down();
      const shot = await page.screenshot({
        clip: { x: box.x, y: box.y, width: box.width, height: box.height },
      });
      if (v.state === 'pressed') await page.mouse.up();
      out.push(PNG.sync.read(shot));
    }
  } finally {
    await browser.close();
  }
  return out;
}

export async function audit({ root = REPO, outDir = null } = {}) {
  const rows = [];
  for (const name of Object.keys(COMPONENTS)) {
    const gPath = join(root, PIXELS, `${name}.geometry.json`);
    const pPath = join(root, PIXELS, `${name}.png`);
    if (!existsSync(gPath) || !existsSync(pPath)) {
      rows.push({ component: name, variant: null, status: 'no-figma-render' });
      continue;
    }
    const geo = readJson(gPath);
    const shot = PNG.sync.read(readFileSync(pPath));
    const k = shot.width / geo.render.width;
    const variants = geo.variants.map((g) => ({ ...g, ...parseVariant(g.name) }));
    // The canvas colour behind the set, read from the screenshot's top-left pixel.
    const [r, g, b] = shot.data;
    const code = await renderCode(name, variants, {
      root,
      scale: k,
      backdrop: `rgb(${r},${g},${b})`,
    });
    variants.forEach((v, i) => {
      const figma = crop(
        shot,
        Math.round(v.x * k),
        Math.round(v.y * k),
        Math.round(v.width * k),
        Math.round(v.height * k),
      );
      const c = compare(code[i], figma);
      if (outDir) {
        const base = join(outDir, `${name}-${v.variant}-${v.size}-${v.state}`);
        mkdirSync(outDir, { recursive: true });
        writeFileSync(`${base}.code.png`, PNG.sync.write(code[i]));
        writeFileSync(`${base}.figma.png`, PNG.sync.write(figma));
        writeFileSync(`${base}.diff.png`, PNG.sync.write(c.diff));
      }
      rows.push({
        component: name,
        variant: v.name,
        sizeCode: c.sizeCode.map((n) => n / k),
        sizeFigma: c.sizeFigma.map((n) => n / k),
        diffPercent: c.diffPercent,
      });
    });
  }
  return rows;
}

export async function run(argv, { log = console.log } = {}) {
  const { arg, root } = cliArgs(argv);
  if (argv.includes('--emit-script')) {
    writeUseFigmaScript(root, 'pixel-geometry.js', buildGeometryScript({ root }), log);
    return 0;
  }
  if (arg('--ingest')) {
    const res = readJson(resolve(arg('--ingest')));
    mkdirSync(join(root, PIXELS), { recursive: true });
    for (const [name, g] of Object.entries(res)) {
      if (!COMPONENTS[name]) throw new Error(`Unknown component ${name}.`);
      writeFileSync(join(root, PIXELS, `${name}.geometry.json`), JSON.stringify(g, null, 2) + '\n');
      log(`wrote ${PIXELS}/${name}.geometry.json (${g.variants.length} variants)`);
    }
    return 0;
  }
  const rows = await audit({ root, outDir: arg('--out') ? resolve(arg('--out')) : null });
  if (argv.includes('--json')) {
    log(JSON.stringify(rows, null, 2));
    return 0;
  }
  for (const r of rows) {
    if (!r.variant) {
      log(
        `${r.component}: no Figma render committed (${PIXELS}/${r.component}.png + .geometry.json)`,
      );
      continue;
    }
    const size =
      r.sizeCode.join('x') === r.sizeFigma.join('x')
        ? r.sizeCode.join('x')
        : `code ${r.sizeCode.join('x')} vs Figma ${r.sizeFigma.join('x')}`;
    log(
      `${r.component.padEnd(11)} ${r.variant.padEnd(44)} ${String(r.diffPercent).padStart(6)}%  ${size}`,
    );
  }
  const done = rows.filter((r) => r.variant);
  const sizeOff = done.filter((r) => r.sizeCode.join('x') !== r.sizeFigma.join('x')).length;
  const mean = done.length
    ? Math.round((done.reduce((a, r) => a + r.diffPercent, 0) / done.length) * 100) / 100
    : 0;
  log(
    `audit-figma-pixels (report): ${done.length} variants · size differs ${sizeOff} · mean pixel diff ${mean}%`,
  );
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await run(process.argv.slice(2));
}
