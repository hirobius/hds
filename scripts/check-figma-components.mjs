#!/usr/bin/env node
/** @internal — not part of @hirobius/design-system public API surface. */
/**
 * scripts/check-figma-components.mjs — Figma component contracts, generated from code.
 *
 * Code is the source of truth (ADR-025). This builds the contract each Figma component
 * must meet (component properties, variable modes, and the variables its layers bind)
 * from src/app/data/component-api.json, and writes it to figma/contracts/<Name>.json.
 *
 * Contracts (owner decision 2026-11-05):
 *   Button      Variant (code's variant union, link included) x Size x State; no iconOnly.
 *   IconButton  Variant (Button's, minus link) x Size x State; Focus and Loading booleans;
 *               an Icon instance swap; the "Button tone" variable modes; a square root bound
 *               to button/size/<s>/height with padding 0, and an "Icon" layer bound to
 *               button/size/<s>/iconSize.
 *
 * It also checks each bound variable and mode collection against figma/snapshot.json, so a
 * contract that names a variable the library does not have shows up before anyone draws it.
 *
 *   node scripts/check-figma-components.mjs            write figma/contracts/*.json
 *   node scripts/check-figma-components.mjs --check    exit 1 if a committed contract is stale
 *   node scripts/check-figma-components.mjs --report   print stale contracts and missing
 *                                                       variables; always exit 0 (pretest)
 *   add --json to --report for a machine-readable result.
 *
 * Talks to Figma? No. Drawing the components is a separate, manual step
 * (figma/COMPONENT-DRAWING-RECIPE.md).
 */
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runGenerator } from './lib/generated-check.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const API_PATH = join(ROOT, 'src/app/data/component-api.json');
const SNAPSHOT_PATH = join(ROOT, 'figma/snapshot.json');
const OUT_DIR = join(ROOT, 'figma/contracts');

const STATES = ['rest', 'hover', 'pressed', 'disabled'];
const TONE_COLLECTION = 'Button tone';
const GENERATED_BY =
  'Generated by scripts/check-figma-components.mjs from src/app/data/component-api.json. Do not edit; run `node scripts/check-figma-components.mjs`.';

/** `"a" | "b" | null` -> ['a', 'b'] */
function unionValues(type) {
  return [...String(type).matchAll(/"([^"]+)"/g)].map((m) => m[1]);
}

function buttonAxes(api) {
  const button = api?.components?.Button;
  const props = Object.fromEntries((button?.props ?? []).map((p) => [p.name, p]));
  for (const name of ['variant', 'size', 'tone']) {
    if (!props[name]) {
      throw new Error(`component-api.json: Button has no "${name}" prop to build contracts from`);
    }
  }
  // Fill weight first, link last: the order a designer reads the Variant dropdown in.
  const order = ['primary', 'secondary', 'tertiary', 'link'];
  const rank = (v) => (order.includes(v) ? order.indexOf(v) : order.length - 1);
  const variants = unionValues(props.variant.type).sort((a, b) => rank(a) - rank(b));
  const sizes = unionValues(props.size.type);
  // The default tone first, then the ghost-only quiet, then the status tones as declared.
  const tones = unionValues(props.tone.type);
  const lead = ['neutral', 'quiet'].filter((t) => tones.includes(t));
  return {
    source: button.filePath,
    variants,
    sizes,
    tones: [...lead, ...tones.filter((t) => !lead.includes(t))],
  };
}

const variable = (s, key) => `button/size/${s}/${key}`;

/** Build the Button and IconButton contracts from the component API. */
export function buildContracts(api) {
  const { source, variants, sizes, tones } = buttonAxes(api);
  const variableModes = { [TONE_COLLECTION]: tones };

  const Button = {
    $comment: GENERATED_BY,
    component: 'Button',
    source,
    properties: {
      Variant: { type: 'VARIANT', values: variants },
      Size: { type: 'VARIANT', values: sizes },
      State: { type: 'VARIANT', values: STATES },
      Focus: { type: 'BOOLEAN', default: false },
      Loading: { type: 'BOOLEAN', default: false },
      Label: { type: 'TEXT' },
      'Icon left': { type: 'INSTANCE_SWAP' },
      'Icon right': { type: 'INSTANCE_SWAP' },
    },
    variantCount: variants.length * sizes.length * STATES.length,
    variableModes,
    notes: [
      'Icon-only buttons are the IconButton component, not a Button property.',
      'Variant=link is plain text in every tone: no fill in any state, and paddingX is 0.',
    ],
    sizes: Object.fromEntries(
      sizes.map((s) => [
        s,
        {
          root: { height: variable(s, 'height'), paddingX: variable(s, 'paddingX') },
          layers: {
            'Icon left': { width: variable(s, 'iconSize'), height: variable(s, 'iconSize') },
            'Icon right': { width: variable(s, 'iconSize'), height: variable(s, 'iconSize') },
          },
        },
      ]),
    ),
  };

  const iconVariants = variants.filter((v) => v !== 'link');
  const IconButton = {
    $comment: GENERATED_BY,
    component: 'IconButton',
    source,
    properties: {
      Variant: { type: 'VARIANT', values: iconVariants },
      Size: { type: 'VARIANT', values: sizes },
      State: { type: 'VARIANT', values: STATES },
      Focus: { type: 'BOOLEAN', default: false },
      Loading: { type: 'BOOLEAN', default: false },
      Icon: { type: 'INSTANCE_SWAP' },
    },
    variantCount: iconVariants.length * sizes.length * STATES.length,
    variableModes,
    notes: [
      'No link variant: an icon with no fill and no label does not read as a link.',
      'In code this is <Button iconOnly label="…" iconLeft={…} />; label is the accessible name.',
    ],
    sizes: Object.fromEntries(
      sizes.map((s) => [
        s,
        {
          root: { width: variable(s, 'height'), height: variable(s, 'height'), padding: 0 },
          layers: { Icon: { width: variable(s, 'iconSize'), height: variable(s, 'iconSize') } },
        },
      ]),
    ),
  };

  return { Button, IconButton };
}

export function serializeContract(contract) {
  return `${JSON.stringify(contract, null, 2)}\n`;
}

/** Names of contracts whose committed file differs from the built one. `read(name)` returns the file text or null. */
export function findStaleContracts(contracts, read) {
  return Object.entries(contracts)
    .filter(([name, contract]) => read(name) !== serializeContract(contract))
    .map(([name]) => name);
}

/** Every bound variable and mode collection a contract names that the snapshot's collections lack. */
export function findMissingVariables(contracts, collections) {
  const names = new Set(collections.flatMap((c) => (c.variables ?? []).map((v) => v.name)));
  const byName = new Map(collections.map((c) => [c.name, c]));
  const found = [];
  for (const [component, contract] of Object.entries(contracts)) {
    const bound = new Set();
    for (const { root, layers } of Object.values(contract.sizes)) {
      for (const value of [
        ...Object.values(root),
        ...Object.values(layers).flatMap(Object.values),
      ]) {
        if (typeof value === 'string') bound.add(value);
      }
    }
    for (const name of [...bound].sort()) {
      if (!names.has(name)) found.push(`${component}: variable ${name} is not in the snapshot`);
    }
    for (const [collection, modes] of Object.entries(contract.variableModes)) {
      const c = byName.get(collection);
      if (!c) {
        found.push(`${component}: variable collection "${collection}" is not in the snapshot`);
        continue;
      }
      const have = new Set((c.modes ?? []).map((m) => (typeof m === 'string' ? m : m.name)));
      for (const mode of modes) {
        if (!have.has(mode)) found.push(`${component}: "${collection}" has no mode "${mode}"`);
      }
    }
  }
  return found;
}

async function main(argv) {
  const report = argv.includes('--report');
  const json = argv.includes('--json');
  const contracts = buildContracts(JSON.parse(readFileSync(API_PATH, 'utf8')));
  const rel = (name) => relative(ROOT, join(OUT_DIR, `${name}.json`));

  // Write and --check go through the shared generator runner (hds#644). The files are
  // in .prettierignore, so the bytes are serializeContract's, unformatted.
  if (!report) {
    const outputs = Object.fromEntries(
      Object.entries(contracts).map(([name, c]) => [rel(name), serializeContract(c)]),
    );
    const { exitCode } = await runGenerator({
      root: ROOT,
      outputs,
      label: 'check-figma-components',
      fix: 'node scripts/check-figma-components.mjs',
      format: false,
      argv,
    });
    return exitCode;
  }

  const read = (name) => {
    const file = join(ROOT, rel(name));
    return existsSync(file) ? readFileSync(file, 'utf8') : null;
  };
  const stale = findStaleContracts(contracts, read);
  const collections = existsSync(SNAPSHOT_PATH)
    ? (JSON.parse(readFileSync(SNAPSHOT_PATH, 'utf8')).snapshot?.collections ?? [])
    : [];
  const missing = findMissingVariables(contracts, collections);

  if (json) {
    console.log(JSON.stringify({ stale, missing }, null, 2));
  } else {
    for (const name of stale) {
      console.log(`⚠ ${rel(name)} is stale: run node scripts/check-figma-components.mjs`);
    }
    for (const line of missing) console.log(`⚠ ${line}`);
    if (!stale.length && !missing.length) {
      console.log(`✓ figma contracts: ${Object.keys(contracts).join(', ')} fresh and bound`);
    } else {
      console.log('  (advisory: --report never fails; --check fails on a stale contract)');
    }
  }
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  process.exitCode = await main(process.argv.slice(2));
}
