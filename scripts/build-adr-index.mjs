#!/usr/bin/env node
/** @internal — not part of @hirobius/design-system public API surface. */
/**
 * build-adr-index.mjs
 *
 * Writes docs/adr/README.md, the index of every ADR: number, title, status,
 * decision date, and whether the record was written retroactively from commit
 * and PR history. The index is generated so it cannot drift from the files;
 * scripts/__tests__/adr-index.test.mjs fails when it is stale.
 *
 * Usage:
 *   node scripts/build-adr-index.mjs           # write docs/adr/README.md
 *   node scripts/build-adr-index.mjs --check   # exit 1 when it is stale
 */

import { readFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runGenerator } from './lib/generated-check.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const ADR_DIR = join(ROOT, 'docs/adr');
const ADR_FILE = /^(\d{3})-.+\.md$/;

/** Number, title, status word, decision date and retroactive flag of one ADR. */
export function parseAdr(file, text) {
  const number = file.match(ADR_FILE)?.[1] ?? '';
  const title = (text.match(/^# ADR-\d+:\s*(.+)$/m)?.[1] ?? '').trim();
  const statusLine = text.match(/\*\*Status:\*\*\s*(.+)$/m)?.[1] ?? '';
  const status = statusLine.match(/^[A-Za-z]+/)?.[0] ?? '';
  const retroactive = /\bretroactive\b/i.test(statusLine);
  const decided = statusLine.match(/decided (\d{4}-\d{2}-\d{2})/)?.[1];
  const date = decided ?? statusLine.match(/\d{4}-\d{2}-\d{2}/)?.[0] ?? '';
  return { number, file, title, status, date, retroactive };
}

export function readAdrs(dir = ADR_DIR) {
  return readdirSync(dir)
    .filter((f) => ADR_FILE.test(f))
    .sort()
    .map((f) => parseAdr(f, readFileSync(join(dir, f), 'utf8')));
}

// Backslashes first, so an escaped pipe cannot be un-escaped by a trailing backslash.
const cell = (s) => s.replace(/\\/g, '\\\\').replace(/\|/g, '\\|');

export function renderIndex(adrs) {
  const retro = adrs.filter((a) => a.retroactive).length;
  const rows = adrs.map(
    (a) =>
      `| [${a.number}](${a.file}) | ${cell(a.title)} | ${a.status} | ${a.date || 'n/a'} | ${a.retroactive ? 'yes' : ''} |`,
  );
  return [
    '<!-- Generated by scripts/build-adr-index.mjs from the ADR files. Do not hand-edit. -->',
    '',
    '# Architecture decision records',
    '',
    'One file per decision, numbered in the order recorded ([ADR-009](009-adr-convention.md)).',
    'An Accepted ADR is not edited; a change is a new ADR that supersedes it through its',
    'Status line.',
    '',
    `${adrs.length} records. ${retro} are **retroactive**: decisions made between June and`,
    'October 2026 that shipped without an ADR, written up afterwards from the commit and PR',
    'history. Each one lists its evidence and says when the evidence does not record a reason.',
    'Their "Decided" date is when the decision landed, not when it was written up.',
    '',
    'The frozen `docs/architecture/ADR-000N` series (multi-tenant scope, the HDSLayout split,',
    'the bundle budget) predates this folder; see ADR-009.',
    '',
    '| ADR | Title | Status | Decided | Retroactive |',
    '| --- | ----- | ------ | ------- | ----------- |',
    ...rows,
    '',
  ].join('\n');
}

async function main() {
  await runGenerator({
    root: ROOT,
    outputs: { 'docs/adr/README.md': renderIndex(readAdrs()) },
    label: 'build-adr-index',
    fix: 'node scripts/build-adr-index.mjs',
  });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
