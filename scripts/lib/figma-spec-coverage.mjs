/**
 * figma-spec-coverage: which library components have a spec sheet in the HDS
 * Figma library, from the committed read-only audit (figma/spec-sheet-audit.json,
 * written by `node scripts/figma-spec-sheets.mjs --ingest`).
 *
 * A component counts when figma/disposition.json classes it `library` and the
 * manifest does not mark it deprecated. It is covered when the library holds a
 * frame named "<Name> — spec sheet", or when the page holding its @figma node
 * holds a spec sheet (a part such as TabsTrigger is specified on its parent's
 * sheet; a part with no @figma tag is found through figma/mapping-overrides.json).
 */
import { SHEET_SUFFIX, figmaNodeIdFromUrl } from './figma-spec-sheet.mjs';

/** The read-only use_figma script that records every page's sheets and component nodes. */
export function auditScript() {
  return `const pages = [];
for (const p of figma.root.children) {
  await p.loadAsync();
  const sheets = p.children.filter((n) => n.type === 'FRAME' && n.name.endsWith(${JSON.stringify(SHEET_SUFFIX)})).map((n) => ({ id: n.id, name: n.name }));
  const nodes = p.findAllWithCriteria({ types: ['COMPONENT', 'COMPONENT_SET'] }).filter((n) => n.parent.type !== 'COMPONENT_SET').map((n) => n.id);
  pages.push({ id: p.id, name: p.name, sheets, nodes });
}
return { fileKey: figma.fileKey, pages };
`;
}

export function normaliseAudit(raw, generatedAt) {
  const pages = (raw.pages ?? [])
    .map((p) => ({
      id: p.id,
      name: p.name,
      sheets: [...p.sheets].sort((a, b) => a.name.localeCompare(b.name)),
      nodes: [...p.nodes].sort(),
    }))
    .sort((a, b) => a.name.localeCompare(b.name) || a.id.localeCompare(b.id));
  return {
    $comment:
      'Generated by `node scripts/figma-spec-sheets.mjs --ingest <use_figma result>` from the read-only script `--emit-audit` prints. Do not hand-edit. scripts/check-figma-spec-coverage.mjs reads it.',
    generatedAt,
    fileKey: raw.fileKey ?? null,
    pages,
  };
}

/**
 * figma/mapping-overrides.json names the Figma node of a part that carries no
 * @figma tag (Sheet.Trigger -> SheetTrigger, TabTrigger -> TabsTrigger).
 */
function overrideNode(name, overrides) {
  const hit = (overrides?.overrides ?? []).find(
    (o) => o.name === name || String(o.mapsTo ?? '').replace(/\./g, '') === name,
  );
  return hit?.nodeId ?? null;
}

export function specCoverage(audit, manifest, disposition, overrides = {}) {
  const sheetNames = new Set();
  const pageOfNode = new Map();
  for (const p of audit.pages) {
    for (const s of p.sheets) sheetNames.add(s.name);
    for (const id of p.nodes) pageOfNode.set(id, p);
  }
  const covered = [];
  const missing = [];
  const exempt = [];
  for (const entry of disposition.components ?? []) {
    const { name } = entry;
    if (entry.class !== 'library') continue;
    const spec = manifest.componentSpecs?.[name];
    if (spec?.deprecated) {
      exempt.push({ name, reason: 'deprecated' });
      continue;
    }
    if (sheetNames.has(name + SHEET_SUFFIX)) {
      covered.push({ name, via: 'own sheet' });
      continue;
    }
    const nodeId =
      figmaNodeIdFromUrl(spec?.figmaUrl ?? entry.figmaUrl) ?? overrideNode(name, overrides);
    const page = nodeId ? pageOfNode.get(nodeId) : null;
    if (page && page.sheets.length) {
      covered.push({ name, via: `${page.name} page sheet` });
      continue;
    }
    missing.push({ name, nodeId, page: page?.name ?? null });
  }
  return { covered, missing, exempt };
}
