/** @internal — not part of @hirobius/design-system public API surface. */
/**
 * figma-code-connect-map: every library component in the HDS Figma library
 * mapped to its code, for Figma Code Connect.
 *
 * The same data the spec-sheet generator reads: figma/disposition.json says
 * which components are `library` (deprecated ones exempt), the manifest gives
 * the source file and the @figma node, figma/mapping-overrides.json gives the
 * node and the code name of a tagless part (Sheet.Trigger, TabsTrigger), and
 * figma/links.json the GitHub blob base. The import entry is the barrel that
 * re-exports the module: src/index.ts (@hirobius/design-system) or
 * src/patterns.ts (@hirobius/design-system/patterns).
 *
 *   codeConnectMap(input) -> { entries[], missing[], exempt[] }
 *   mappingsPayload(file) -> the `mappings` array for the Figma MCP tool
 *     send_code_connect_mappings: one simple React mapping per entry (node,
 *     code name, GitHub source). The import and usage snippet live in the
 *     committed map; the rich variant templates stay in figma/code-connect.json.
 *     Saving a mapping needs a Figma Organization or Enterprise plan (ADR-019 §3).
 */
import { figmaNodeIdFromUrl } from './figma-spec-sheet.mjs';

const ROOT_ENTRY = '@hirobius/design-system';
const PATTERNS_ENTRY = '@hirobius/design-system/patterns';
const JSX_NAME = /^[A-Z][A-Za-z0-9]*(\.[A-Z][A-Za-z0-9]*)?$/;

function override(name, overrides) {
  return (
    (overrides?.overrides ?? []).find(
      (o) => o.name === name || String(o.mapsTo ?? '').replace(/\./g, '') === name,
    ) ?? null
  );
}

/** `src/app/components/alert.tsx` -> `./app/components/alert`, as a barrel writes it. */
const modulePath = (filePath) => './' + filePath.replace(/^src\//, '').replace(/\.tsx?$/, '');

function entryFor(filePath, barrels) {
  const re = new RegExp(`from ['"]${modulePath(filePath).replace(/[.]/g, '\\.')}['"]`);
  if (re.test(barrels.root ?? '')) return ROOT_ENTRY;
  if (re.test(barrels.patterns ?? '')) return PATTERNS_ENTRY;
  return null;
}

const placeholder = (type) => (/^string\b/.test(String(type ?? '')) ? '"…"' : '{…}');

/** A usage line: the component with its required props (children go between the tags). */
export function usageSnippet(componentName, spec = {}) {
  const required = (spec.requiredProps ?? []).filter((p) => p !== 'children');
  const attrs = required.map((p) => ` ${p}=${placeholder(spec.props?.[p]?.type)}`).join('');
  const hasChildren =
    (spec.requiredProps ?? []).includes('children') || 'children' in (spec.props ?? {});
  return hasChildren
    ? `<${componentName}${attrs}>…</${componentName}>`
    : `<${componentName}${attrs} />`;
}

export function codeConnectMap({ manifest, disposition, overrides = {}, links, barrels, exists }) {
  const specs = manifest.componentSpecs ?? {};
  const base = `${links.repository}/blob/${links.branch}`;
  const entries = [];
  const missing = [];
  const exempt = [];
  for (const c of disposition.components ?? []) {
    if (c.class !== 'library') continue;
    const spec = specs[c.name] ?? {};
    if (spec.deprecated) {
      exempt.push({ name: c.name, reason: 'deprecated' });
      continue;
    }
    const o = override(c.name, overrides);
    const nodeId = figmaNodeIdFromUrl(spec.figmaUrl ?? c.figmaUrl) ?? o?.nodeId ?? null;
    const source = spec.filePath ?? o?.source ?? null;
    const componentName = o && JSX_NAME.test(o.mapsTo ?? '') ? o.mapsTo : c.name;
    const why = [];
    if (!nodeId)
      why.push('no Figma node (no @figma tag and no figma/mapping-overrides.json entry)');
    if (!source) why.push('no source file in the manifest');
    else if (!exists(source)) why.push(`source ${source} does not exist`);
    const entry = source ? entryFor(source, barrels) : null;
    if (source && !entry)
      why.push(`${source} is re-exported by neither src/index.ts nor src/patterns.ts`);
    if (why.length) {
      missing.push({ name: c.name, why });
      continue;
    }
    const root = componentName.split('.')[0];
    entries.push({
      name: c.name,
      nodeId,
      componentName,
      source,
      sourceUrl: `${base}/${source}`,
      import: `import { ${root} } from '${entry}';`,
      snippet: usageSnippet(componentName, spec),
    });
  }
  entries.sort((a, b) => a.name.localeCompare(b.name));
  return { entries, missing, exempt };
}

export function mapFile(map, fileKey) {
  return {
    $comment:
      'Generated by `node scripts/figma-code-connect-map.mjs --write` from figma/disposition.json, public/hds-manifest.json, figma/mapping-overrides.json and figma/links.json. Do not hand-edit. scripts/check-code-connect-map.mjs fails when a library component has no mapping or this file is stale. `--emit-mappings` prints the payload for the Figma MCP tool send_code_connect_mappings (needs a Figma Organization plan, ADR-019 §3).',
    fileKey,
    label: 'React',
    entries: map.entries,
    exempt: map.exempt,
  };
}

/** The `mappings` argument of send_code_connect_mappings, one per entry. */
export function mappingsPayload(file) {
  return file.entries.map((e) => ({
    nodeId: e.nodeId,
    componentName: e.componentName,
    source: e.sourceUrl,
    label: file.label,
  }));
}
