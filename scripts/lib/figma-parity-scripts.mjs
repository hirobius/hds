/** @internal — not part of @hirobius/design-system public API surface. */
/**
 * Builds the read-only use_figma scripts of the parity read
 * (scripts/lib/figma-parity-runtime.mjs). Same carrier rules as every other
 * use_figma script here (scripts/lib/figma-scripts.mjs): the library guard is
 * the first statement, and the runtime checks its own code before it reads.
 */
import {
  agentRuntimeSource,
  deltaRuntimeSource,
  emitVerifiedRuntime,
  reachableRuntime,
  runtimeSource,
  snapshotDiffRuntimeSource,
  syncConfigFromLinks,
  syncRuntimeSource,
  useFigmaLibraryGuard,
} from './figma-scripts.mjs';
import { readFileSync } from 'node:fs';

/** A use_figma result holds about 20 KB (figma/SYNC-PROCEDURE.md). */
export const PARITY_RESULT_CHARS = 18000;
/** Parts the components read starts with; raise it when a part returns `tooLarge`. */
export const PARITY_COMPONENT_PARTS = 4;

/** figma-parity-runtime.mjs as a script body: no comments, imports or `export`. */
function parityRuntimeSource() {
  const source = readFileSync(new URL('./figma-parity-runtime.mjs', import.meta.url), 'utf8');
  return source
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^import [\s\S]*?;\n/gm, '')
    .replace(/^export (async )?function /gm, (_m, isAsync) => `${isAsync ?? ''}function `)
    .trim();
}

const source = () =>
  [
    runtimeSource(),
    deltaRuntimeSource(),
    syncRuntimeSource(),
    agentRuntimeSource(),
    snapshotDiffRuntimeSource(),
    parityRuntimeSource(),
  ].join('\n\n');

const header = (lines) => lines.map((line) => `// ${line}`).join('\n');

/** The variables read. `file` is the committed snapshot's `snapshot.file`. */
export function buildParityVariablesScript(links, file) {
  return [
    useFigmaLibraryGuard(syncConfigFromLinks(links), 'The parity read reads the library only.'),
    header([
      'HDS figma:parity, variables. Read only. Generated by `pnpm figma:parity --emit-read`; run it unmodified.',
      'Save the returned JSON to a file, then: pnpm figma:parity --ingest <every saved file>',
    ]),
    '',
    emitVerifiedRuntime(reachableRuntime(['hdsParityVariables'], source())),
    `return await hdsParityVariables(figma, ${JSON.stringify(file)});`,
    '',
  ].join('\n');
}

/** Part `part` of `parts` of the components read. */
export function buildParityComponentsScript(links, part, parts = PARITY_COMPONENT_PARTS) {
  return [
    useFigmaLibraryGuard(syncConfigFromLinks(links), 'The parity read reads the library only.'),
    header([
      `HDS figma:parity, components part ${part + 1} of ${parts}. Read only. Generated by \`pnpm figma:parity --emit-read\`; run it unmodified.`,
      'Save the returned JSON to a file, then: pnpm figma:parity --ingest <every saved file>',
    ]),
    '',
    emitVerifiedRuntime(reachableRuntime(['hdsParityComponents'], source())),
    `return await hdsParityComponents(figma, ${part}, ${parts}, ${PARITY_RESULT_CHARS});`,
    '',
  ].join('\n');
}
