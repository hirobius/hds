/** @internal — not part of @hirobius/design-system public API surface. */
/**
 * Hirobius Design System — the code a `pnpm figma:links` descriptions script
 * runs inside Figma (readiness plan A8).
 *
 * buildDescriptionsScript (scripts/lib/design-links.mjs) reads the source text
 * of every function this file exports, plus hdsChecksum from figma-runtime.mjs,
 * and puts it in the script. An agent retypes the script into use_figma's `code`
 * parameter, so before it reads or writes anything the script checks two
 * checksums: one over its payload, and one over the source of every function it
 * carries. Only the two call lines that close the script are not covered. So
 * every function here stays self-contained: it may use hdsChecksum and the
 * functions in this file, and nothing else.
 *
 * What a run writes to each linked component set, and what it keeps:
 *   - Description: an HDS block (import line, JSDoc description, source path)
 *     between a "▼ HDS" line and a "▲ HDS" line. Text outside the block is
 *     never changed: the first run appends the block, later runs replace only
 *     the block. A damaged block (a marker missing, repeated or out of order)
 *     is refused and nothing is written to that node. Where the file has
 *     rich-text descriptions (descriptionMarkdown and figma.util.normalizeMarkdown),
 *     the block goes through descriptionMarkdown, so formatting outside it
 *     survives, unless descriptionMarkdown reads empty next to a non-empty
 *     plain description (a stale read the Plugin API typings warn about).
 *   - Documentation link (Figma holds one): set when there is none, replaced
 *     only when a previous run set it (recorded as shared plugin data), and
 *     otherwise kept and reported.
 */

import { hdsChecksum } from './figma-runtime.mjs';

/**
 * Refuses a script whose code changed after `pnpm figma:links` generated it.
 * `functions` is every function the script carries; `checksum` is hdsChecksum
 * of their source text joined by newlines. Carriage returns are ignored.
 */
export function hdsLinksVerifyCode(functions, checksum) {
  const texts = functions.map((fn) => String(fn).replace(/\r/g, ''));
  if (texts.some((text) => /\{\s*\[native code\]\s*\}\s*$/.test(text))) {
    throw new Error(
      'This Figma runtime does not expose function source, so the script cannot check its own code. Nothing was read or written.',
    );
  }
  if (hdsChecksum(texts.join('\n')) !== checksum) {
    throw new Error(
      "The script's code does not match its checksum: it changed after pnpm figma:links generated it (a copy or transcription error). Nothing was read or written. Regenerate with pnpm figma:links and run the script unmodified.",
    );
  }
}

/** The HDS block for one component; `markdown` wraps code in backticks. */
export function hdsLinksBlock(item, markdown) {
  const code = (text) => (markdown ? '`' + text + '`' : text);
  return [
    '▼ HDS · generated by pnpm figma:links from the component JSDoc · edits inside this block are replaced',
    code(item.importLine),
    item.summary,
    'Source: ' + code(item.sourcePath),
    '▲ HDS',
  ]
    .filter(Boolean)
    .join('\n\n');
}

/**
 * `text` with `block` in place of its HDS block, or appended after it when it
 * has none. `{ problem }` when the block is damaged.
 */
export function hdsLinksSplice(text, block) {
  const start = '▼ HDS';
  const end = '▲ HDS';
  const starts = text.split(start).length - 1;
  const ends = text.split(end).length - 1;
  if (starts === 0 && ends === 0) {
    const kept = text.replace(/\s+$/, '');
    return { text: kept ? kept + '\n\n' + block : block };
  }
  const from = text.indexOf(start);
  const to = text.indexOf(end);
  if (starts !== 1 || ends !== 1 || to < from) {
    return {
      problem:
        'its description has a damaged HDS block (the ▼ HDS and ▲ HDS lines must each appear once, in that order). Nothing was written to it: fix or delete the block in Figma, then run the script again.',
    };
  }
  return { text: text.slice(0, from) + block + text.slice(to + end.length) };
}

/**
 * Sets the HDS block and documentation link on each component in the payload.
 *
 * @param {object} figma     The Plugin API.
 * @param {{ dryRun: boolean, items: Array<{ component: string, nodeId: string, importLine: string, summary: string, sourcePath: string, documentationLink: string }> }} payload
 * @param {string} checksum  hdsChecksum(JSON.stringify(payload)) from `pnpm figma:links`.
 */
export async function hdsApplyDescriptions(figma, payload, checksum) {
  if (hdsChecksum(JSON.stringify(payload)) !== checksum) {
    throw new Error(
      'The descriptions payload does not match its checksum: it changed after pnpm figma:links generated it. Nothing was written. Regenerate with pnpm figma:links and run the script unmodified.',
    );
  }
  const namespace = 'hirobius';
  const linkKey = 'documentationLink';
  const normalize =
    figma.util && typeof figma.util.normalizeMarkdown === 'function'
      ? (text) => figma.util.normalizeMarkdown(text)
      : null;
  const report = {
    file: figma.root.name,
    dryRun: payload.dryRun,
    updated: [],
    unchanged: [],
    keptLinks: [],
    refused: [],
    notFound: [],
    notComponent: [],
  };
  for (const item of payload.items) {
    const node = await figma.getNodeByIdAsync(item.nodeId);
    if (!node) {
      report.notFound.push(item.component + ': node ' + item.nodeId);
      continue;
    }
    if (node.type !== 'COMPONENT' && node.type !== 'COMPONENT_SET') {
      report.notComponent.push(item.component + ': node ' + item.nodeId + ' is a ' + node.type);
      continue;
    }

    // Figma can report a stale, empty descriptionMarkdown next to a real
    // description; writing the block there would replace that text.
    const markdown =
      normalize !== null &&
      typeof node.descriptionMarkdown === 'string' &&
      (node.descriptionMarkdown.trim() !== '' || (node.description || '').trim() === '');
    const field = markdown ? 'descriptionMarkdown' : 'description';
    const current = node[field] || '';
    const spliced = hdsLinksSplice(current, hdsLinksBlock(item, markdown));
    if (spliced.problem) {
      report.refused.push(item.component + ': ' + spliced.problem);
      continue;
    }
    const description = markdown ? normalize(spliced.text) : spliced.text;

    const links = (node.documentationLinks || []).map((link) => link.uri);
    const setByHds =
      links.length === 1 && links[0] === node.getSharedPluginData(namespace, linkKey);
    let setLink = false;
    if (!links.includes(item.documentationLink)) {
      if (links.length === 0 || setByHds) {
        setLink = true;
      } else {
        report.keptLinks.push(
          item.component +
            ': keeps its documentation link ' +
            links.join(', ') +
            ', which pnpm figma:links did not set (Figma holds one link). Remove it in Figma to get the story link.',
        );
      }
    }

    const changes = [];
    if (description !== current) changes.push(field);
    if (setLink) changes.push('documentationLinks');
    if (changes.length === 0) {
      report.unchanged.push(item.component);
      continue;
    }
    report.updated.push({
      component: item.component,
      node: node.name,
      changes,
      previousDescription: current,
      previousLinks: links,
    });
    if (!payload.dryRun) {
      if (description !== current) node[field] = description;
      if (setLink) {
        node.documentationLinks = [{ uri: item.documentationLink }];
        node.setSharedPluginData(namespace, linkKey, item.documentationLink);
      }
    }
  }
  return report;
}
