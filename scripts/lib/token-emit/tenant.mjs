/**
 * Tenant / accent overlay emitter: overlay validation, the deprecated-alias
 * index and the [data-brand] / [data-accent] CSS. Reads tenants/<slug>/tokens.json
 * only when buildTenantCSS is called; split out of scripts/build-tokens.mjs (hds#645).
 */

import { readFileSync, readdirSync, existsSync } from 'fs';
import { join } from 'path';
import { readModes } from '../token-modes.mjs';
import { overlayEdgeVars } from '../raised-edge.mjs';
import { resolveAlias, walkTokens } from '../token-tree.mjs';
import { pathToCSSVar, valueToCSS } from './css.mjs';

// ── Tenant overlay validator ────────────────────────────────────────────────
/**
 * Validates a tenant tokens.json overlay against HDS structural rules.
 *
 * Rules (per docs/architecture/tenant-token-overlay-format.md):
 *   R1 — No primitive-tier overrides (path[0] must not be "primitive")
 *   R5 — Every override path must exist in the base token graph
 *   R8 — All alias {ref} values must resolve against the base graph
 *
 * @param {object} overlay   - Parsed tenant tokens.json (partial DTCG)
 * @param {object} baseRaw   - Parsed hirobius.tokens.json (full DTCG)
 * @param {string} slug      - Tenant slug (for error context)
 * @returns {string[]}       - Array of error strings; empty = pass
 */
export function validateTenantOverlay(overlay, baseRaw, slug) {
  const errors = [];

  // Build flat path set from base for R5 checks
  const basePathIndex = new Set();
  for (const { path } of walkTokens(baseRaw)) {
    basePathIndex.add(path.join('.'));
  }

  for (const { path, value } of walkTokens(overlay)) {
    const dotPath = path.join('.');
    const tier = path[0];

    // R1 — no primitive overrides
    if (tier === 'primitive') {
      errors.push(
        `R1 [${slug}:${dotPath}] primitive-tier override is forbidden — override semantic-tier tokens instead`,
      );
    }

    // R5 — path must exist in base
    if (!basePathIndex.has(dotPath)) {
      errors.push(
        `R5 [${slug}:${dotPath}] path does not exist in hirobius.tokens.json — tenants override only; they do not extend`,
      );
    }

    // R8 — alias must resolve against base
    const isAlias = typeof value === 'string' && value.startsWith('{');
    if (isAlias) {
      try {
        resolveAlias(value, baseRaw);
      } catch (e) {
        errors.push(`R8 [${slug}:${dotPath}] alias "${value}" — ${e.message}`);
      }
    }
  }

  return errors;
}

// ── Deprecated-alias index ─────────────────────────────────────────────────────
/**
 * Maps each canonical token path to the CSS vars of its `$deprecated` aliases
 * (base leaves whose `$value` is exactly `{canonical.path}`), e.g.
 * `semantic.space.surface.padding` → [`--semantic-space-component-padding`] (until
 * hds#625 removed that alias).
 *
 * Why: tokens.generated.css declares an alias on :root as `var(--canonical)`, and a
 * custom property is computed where it is declared. A tenant overlay that
 * overrides the canonical var on a descendant `[data-brand]` element (a
 * docs or app brand switcher does exactly that) would therefore never reach a
 * consumer still reading the deprecated alias. buildTenantCSS redeclares
 * each such alias beside the override so renaming a token (hds#206) keeps
 * every computed value the same until the alias is removed.
 *
 * @param {object} baseRaw - Parsed hirobius.tokens.json
 * @returns {Map<string, string[]>}
 */
export function indexDeprecatedAliases(baseRaw) {
  const index = new Map();
  for (const { path, value, deprecated, extensions } of walkTokens(baseRaw)) {
    if (!deprecated || typeof value !== 'string') continue;
    // A themed alias (its Dark differs from $value) cannot be re-anchored to one
    // var without pinning its Light value in dark mode; it keeps the :root value.
    const dark = readModes(extensions)?.Dark;
    if (dark !== undefined && dark !== value) continue;
    const m = /^\{([^}]+)\}$/.exec(value);
    if (!m) continue;
    const list = index.get(m[1]) ?? [];
    list.push(pathToCSSVar(path));
    index.set(m[1], list);
  }
  return index;
}

// ── Per-tenant CSS emitter ─────────────────────────────────────────────────────
export const TENANT_HEADER = [
  '/**',
  ' * Generated by scripts/build-tokens.mjs — do not edit manually.',
  // Never write "*" followed by "/" in this header: it closes the comment early
  // and the leftover text invalidates the first tenant rule.
  ' * Source: tenants/<slug>/tokens.json (W3C DTCG overlay format)',
  ' * Regenerate: node scripts/build-tokens.mjs',
  ' *',
  ' * Per-brand token overrides using [data-brand="slug"] attribute selectors',
  ' * (data-tenant kept as a supported alias — #62). Strategy: ADR-0001.',
  ' * Set <html data-brand="slug"> at the app root to activate a brand overlay.',
  ' * Dark overrides: [data-brand="slug"][data-theme="dark"] (specificity 0,2,0).',
  ' * Density overrides: [data-brand="slug"][data-density="compact"] (ADR-022).',
  ' */',
];

export const ACCENT_HEADER = [
  '/**',
  ' * Generated by scripts/build-tokens.mjs — do not edit manually.',
  ' * Source: accents/<name>/tokens.json (same overlay format and rules as a tenant)',
  ' * Regenerate: node scripts/build-tokens.mjs',
  ' *',
  ' * Opt-in accent themes. Graphite is the default accent; set data-accent="<name>"',
  ' * on <html> (or any wrapper) to swap the accent tokens only. Dark overrides:',
  ' * [data-accent="<name>"][data-theme="dark"]. A data-brand overlay loads after this',
  ' * file, so a tenant accent wins when both are set on the same element.',
  ' */',
];

/**
 * One overlay's declarations: light (its Light mode, else $value), dark and
 * compact-density lines for every overridden leaf, each followed by its
 * re-anchored $deprecated aliases (hds#206).
 */
function overlayDeclarations(overlay, baseRaw, deprecatedAliases) {
  // Collect light, dark, and compact-density CSS vars for each overridden leaf
  const lightVars = [];
  const darkVars = [];
  const densityVars = [];

  for (const { path, type, value, extensions } of walkTokens(overlay)) {
    const cssVar = pathToCSSVar(path);
    const aliasVars = deprecatedAliases.get(path.join('.')) ?? [];
    /** Redeclares this leaf's $deprecated aliases next to its override (hds#206). */
    const reanchor = (list) => {
      for (const aliasVar of aliasVars) {
        list.push(
          `  ${aliasVar}: var(${cssVar}); /* deprecated alias re-anchored to the override (hds#206) */`,
        );
      }
    };

    // Composite types (typography, transition, motion, elevation) require
    // the full base context for expansion. Skip atomic-string passthrough
    // for now; simple scalar overrides (color, dimension, fontFamily, etc.)
    // cover the common case and match the documented overlay format.
    if (
      type === 'typography' ||
      type === 'transition' ||
      type === 'motion' ||
      type === 'elevation'
    ) {
      if (typeof value === 'string') {
        lightVars.push(
          `  ${cssVar}: ${value}; /* css-ok: tenant palette primitive */ /* tier-ok: tenant primitive override is the override mechanism — semantic alias */`,
        );
      }
      continue;
    }

    // Prefer explicit Light mode value if present, fall back to $value
    const modes = readModes(extensions);
    const lightMode = modes?.Light;
    const darkMode = modes?.Dark;
    const compactMode = modes?.Compact;

    const lightVal = lightMode ?? value;
    const darkVal = darkMode;
    const compactVal = compactMode;

    // Emit light value. /* css-ok */ marker tells check-css-values that
    // raw hex/dimension values at the tenant primitive layer are intentional —
    // every other layer references vars, but the tenant overlay IS where the
    // primitive concrete value lives (see ADR-0001 multi-tenant scope).
    if (lightVal != null) {
      const cssValue = valueToCSS(lightVal, type, /* preserveAlias */ true, baseRaw);
      if (cssValue != null) {
        lightVars.push(
          `  ${cssVar}: ${cssValue}; /* css-ok: tenant palette primitive */ /* tier-ok: tenant primitive override is the override mechanism — semantic alias */`,
        );
        reanchor(lightVars);
      }
    }

    // Emit dark value only when it differs from light
    if (darkVal != null && darkVal !== lightVal) {
      const cssValue = valueToCSS(darkVal, type, /* preserveAlias */ true, baseRaw);
      if (cssValue != null) {
        darkVars.push(
          `  ${cssVar}: ${cssValue}; /* css-ok: tenant palette primitive */ /* tier-ok: tenant primitive override is the override mechanism — semantic alias */`,
        );
        reanchor(darkVars);
      }
    }

    // Emit compact-density value only when it differs from the rest value
    // (ADR-022 — shape/density overlay axis).
    if (compactVal != null && compactVal !== lightVal) {
      const cssValue = valueToCSS(compactVal, type, /* preserveAlias */ true, baseRaw);
      if (cssValue != null) {
        densityVars.push(
          `  ${cssVar}: ${cssValue}; /* css-ok: tenant palette primitive */ /* tier-ok: tenant primitive override is the override mechanism — semantic alias */`,
        );
        reanchor(densityVars);
      }
    }
  }
  return { lightVars, darkVars, densityVars };
}

/**
 * Walks tenants/* (skipping _template and any dir without tokens.json),
 * validates each overlay, and returns CSS text for tenants.css.
 *
 * Scope strategy: [data-tenant="<slug>"] attribute selectors (ADR-0001).
 * Dark overrides emit under [data-tenant="<slug>"][data-theme="dark"].
 * Density overrides (shape/space overlays — ADR-022) emit under
 * [data-tenant="<slug>"][data-density="compact"], sourced from a leaf's
 * `$extensions.com.figma.variables.modes.Compact` value — the same
 * mode-map convention R4 already uses for Light/Dark, extended with a third
 * named mode. Theme and density combine with brand independently (no triple
 * brand×theme×density block), per ADR-022's chosen option.
 *
 * @param {string}   tenantsDir  - Absolute path to the tenants/ directory
 * @param {object}   baseRaw     - Parsed hirobius.tokens.json
 * @param {object}   [options]
 * @param {boolean}  [options.strict=true]  - Skip emitting tenants with validation errors
 * @param {string[]} [options.attributes]   - Attributes that activate an overlay (default data-brand, data-tenant; accents/ uses data-accent)
 * @param {string[]} [options.header]       - Header comment lines for the emitted file
 * @returns {{ css: string, tenants: string[], errors: string[] }}
 */
export function buildTenantCSS(
  tenantsDir,
  baseRaw,
  {
    strict = true,
    attributes = ['data-brand', 'data-tenant'],
    header: headerLines = TENANT_HEADER,
  } = {},
) {
  const allErrors = [];
  const processedSlugs = [];
  const blocks = [];
  const deprecatedAliases = indexDeprecatedAliases(baseRaw);

  let slugDirs;
  try {
    slugDirs = readdirSync(tenantsDir, { withFileTypes: true });
  } catch {
    // tenants/ directory doesn't exist — nothing to emit
    return { css: '', tenants: [], errors: [] };
  }

  for (const entry of slugDirs) {
    if (!entry.isDirectory()) continue;
    const slug = entry.name;
    // Skip reserved directories (e.g. _template)
    if (slug.startsWith('_')) continue;
    // Validate slug format: lowercase, kebab-case, ASCII
    if (!/^[a-z0-9-]+$/.test(slug)) {
      allErrors.push(`[${slug}] invalid slug format — must match [a-z0-9-]+`);
      continue;
    }

    const overlayPath = join(tenantsDir, slug, 'tokens.json');
    if (!existsSync(overlayPath)) continue;

    let overlay;
    try {
      overlay = JSON.parse(readFileSync(overlayPath, 'utf8'));
    } catch (e) {
      allErrors.push(`[${slug}] JSON parse error in tokens.json: ${e.message}`);
      continue;
    }

    // Validate overlay against base token graph
    const errs = validateTenantOverlay(overlay, baseRaw, slug);
    if (errs.length > 0) {
      allErrors.push(...errs);
      if (strict) continue; // skip emitting this tenant when validation fails
    }

    const { lightVars, darkVars, densityVars } = overlayDeclarations(
      overlay,
      baseRaw,
      deprecatedAliases,
    );

    // Raised edges (hds#897): an overlay that moves an edge fill re-derives its edge.
    const edges = overlayEdgeVars(baseRaw, overlay);
    lightVars.push(...edges.light);
    darkVars.push(...edges.dark);

    if (lightVars.length === 0 && darkVars.length === 0 && densityVars.length === 0) continue;

    processedSlugs.push(slug);

    const bar = '─'.repeat(Math.max(0, 68 - slug.length));
    let block = `\n/* ── ${slug} ${bar} */\n`;
    // #62: data-brand is the primary attribute; data-tenant is kept as a
    // supported alias. The grouped selector activates the overlay for either.
    const selector = (suffix = '') =>
      attributes.map((attr) => `[${attr}="${slug}"]${suffix}`).join(',\n');
    block += `${selector()} {\n${lightVars.join('\n')}\n}\n`;

    if (darkVars.length > 0) {
      block += `${selector('[data-theme="dark"]')} {\n${darkVars.join('\n')}\n}\n`;
    }

    // Density block (ADR-022): brand × density, independent of brand × theme
    // above — no triple-combo block, density and theme both layer on brand.
    if (densityVars.length > 0) {
      block += `${selector('[data-density="compact"]')} {\n${densityVars.join('\n')}\n}\n`;
    }

    blocks.push(block);
  }

  const header = headerLines.join('\n');

  const css = blocks.length > 0 ? header + blocks.join('') : '';

  return { css, tenants: processedSlugs, errors: allErrors };
}
