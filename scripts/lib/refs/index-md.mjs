/** @internal — pure helpers for the design-refs pipeline (eval/refs/README.md). */
/**
 * eval/refs/INDEX.md: the one file a build agent reads instead of looking at
 * any image. A table of every ref, the recurring gaps, then every card in
 * full. Generated (`pnpm eval:refs --index --write`), and `--check` fails when
 * the committed file is stale.
 */

const cell = (v) =>
  String(v ?? '')
    .replace(/\|/g, '\\|')
    .replace(/\n/g, ' ');

/**
 * @param {{ id:string, meta:object, gapIds:string[], card:string }[]} refs valid refs, any order
 * @param {{ candidates:object[], logged:object[], suppressed:object[] }} clusters from clusterGaps
 * @param {{ threshold:number }} opts
 */
export function renderIndex(refs, clusters, { threshold }) {
  const sorted = [...refs].sort((a, b) => b.id.localeCompare(a.id));
  const lines = [
    '# Design refs index',
    '',
    '<!-- Generated by `pnpm eval:refs --index --write`. Do not edit by hand; edit the ref and regenerate. -->',
    '',
    'Images Adrian saved for taste, each rebuilt with only the current HDS package. Read this',
    'instead of the images (they are not in the repo). Before building a screen like one of',
    "these, read its card and copy the rebuild's patterns from `eval/refs/refs/<id>/src/App.tsx`:",
    'that file is the reference build, already lint-clean and on the system. A gap below is',
    'something HDS cannot do yet: do not invent a one-off for it; note it in your own gap log.',
    'How the pipeline works: `eval/refs/README.md`.',
    '',
    `${refs.length} ref${refs.length === 1 ? '' : 's'}. A gap becomes a proposal when ${threshold} or more refs hit it.`,
    '',
  ];
  if (sorted.length === 0) {
    lines.push('No refs yet. The nightly run adds one per new image in Drive "Design Refs".', '');
  } else {
    lines.push(
      '| Ref | Title | Surface | Viewport | Fidelity | Gaps |',
      '| --- | --- | --- | --- | --- | --- |',
    );
    for (const r of sorted) {
      const f = r.meta.fidelity;
      const fidelity = f ? `${f.score}/100` : 'not scored';
      lines.push(
        `| [\`${r.id}\`](refs/${r.id}/card.md) | ${cell(r.meta.title)} | ${r.meta.surface} | ${r.meta.viewport} ${r.meta.theme} | ${fidelity} | ${r.gapIds.map((g) => `\`${g}\``).join(' ') || 'none'} |`,
      );
    }
    lines.push('');
  }

  const recurring = [...clusters.candidates, ...clusters.suppressed, ...clusters.logged];
  if (recurring.length) {
    lines.push(
      '## Gaps across refs',
      '',
      '| Gap | Kind | Refs | State |',
      '| --- | --- | --- | --- |',
    );
    for (const g of recurring) {
      lines.push(`| \`${g.id}\` | ${g.kind} | ${g.refCount} | ${g.state} |`);
    }
    lines.push('');
  }

  if (sorted.length) {
    lines.push('## Cards', '');
    for (const r of sorted) {
      const body = r.card
        .trim()
        .split('\n')
        .map((l) => (l.startsWith('#') ? `##${l}` : l));
      lines.push(...body, '', `Rebuild: \`eval/refs/refs/${r.id}/src/App.tsx\``, '');
    }
  }
  return `${lines.join('\n').trimEnd()}\n`;
}
