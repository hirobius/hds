#!/usr/bin/env node
/** @internal — not part of @hirobius/design-system public API surface. */
/**
 * scripts/check-figma-bindings.mjs — do the library's components bind the same
 * component.* variables that the code binds? (hds#595, hds#1147)
 *
 * Code side: check-component-token-binding (--json) classifies every component
 * token leaf (BOUND, LITERAL-MATCH, LITERAL-MISMATCH, UNUSED).
 * Figma side: figma/bindings.json, a read-only use_figma snapshot of the variables
 * each component set binds on any of its layers. Only variables of the
 * "Hirobius/Component" collection count; a "Button tone" variable counts as the
 * component variables it aliases.
 *
 * Each token gets one status:
 *   both             code uses the token (any class but UNUSED) and Figma binds it
 *   code-only        code uses it; Figma does not bind it
 *   figma-only       Figma binds it; code leaves it UNUSED
 *   neither          UNUSED in code and not bound in Figma
 *   not-snapshotted  the group's Figma set is not in figma/bindings.json
 *
 * Usage:
 *   node scripts/check-figma-bindings.mjs                report (default), exit 0
 *   node scripts/check-figma-bindings.mjs --json         the rows as JSON
 *   node scripts/check-figma-bindings.mjs --emit-script  write figma/push/use-figma/bindings-snapshot.js
 *   node scripts/check-figma-bindings.mjs --ingest <f>   verify and write figma/bindings.json
 *
 * Report mode only: it never fails. Never writes to Figma.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { hdsChecksum } from './lib/figma-runtime.mjs';
import { COMPONENTS } from './check-figma-components.mjs';

const REPO = join(dirname(fileURLToPath(import.meta.url)), '..');
const BINDINGS = 'figma/bindings.json';
const SCRIPT_MAX_CHARS = 40000;

const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));
const stable = (v) =>
  Array.isArray(v)
    ? v.map(stable)
    : v && typeof v === 'object'
      ? Object.fromEntries(
          Object.keys(v)
            .sort()
            .map((k) => [k, stable(v[k])]),
        )
      : v;

/**
 * Each token group in scripts/component-token-bindings.json -> the Figma component
 * sets to read. A source under component parity (check-figma-components) uses those
 * node ids; any other source uses the first @figma tag in its file.
 */
export function bindingTargets({ root = REPO } = {}) {
  const map = readJson(join(root, 'scripts/component-token-bindings.json'));
  const out = [];
  for (const [group, g] of Object.entries(map.groups)) {
    if (!g.source) continue;
    const parity = Object.values(COMPONENTS)
      .filter((c) => c.source === g.source && c.nodeId)
      .map((c) => c.nodeId);
    if (parity.length) {
      out.push({ group, nodeIds: parity });
      continue;
    }
    const src = readFileSync(join(root, g.source), 'utf8');
    const m = src.match(/@figma https:\/\/\S*node-id=(\d+)-(\d+)/);
    if (m) out.push({ group, nodeIds: [`${m[1]}:${m[2]}`] });
  }
  return out;
}

export function buildBindingsScript({ root = REPO } = {}) {
  const links = readJson(join(root, 'figma/links.json'));
  const retired = (links.retiredFiles || []).map((f) => f.fileKey);
  const ids = [...new Set(bindingTargets({ root }).flatMap((t) => t.nodeIds))];
  const script = `// HDS component bindings snapshot. Generated by scripts/check-figma-bindings.mjs --emit-script; run it unmodified.
// Reads only. Save the returned JSON, then: node scripts/check-figma-bindings.mjs --ingest <file>
if (figma.fileKey !== '${links.libraryFileKey}' || ${JSON.stringify(retired)}.indexOf(figma.fileKey) !== -1) {
  throw new Error('Refused: this is not the HDS library (${links.libraryFileKey}). Nothing was read or written.');
}
${hdsChecksum.toString()}
const stable = ${stable.toString()};
const IDS = [${ids.map((i) => `'${i}'`).join(', ')}];
const cols = {};
for (const c of await figma.variables.getLocalVariableCollectionsAsync()) cols[c.id] = c.name;
const vars = {};
const getVar = async (id) => { if (!(id in vars)) vars[id] = await figma.variables.getVariableByIdAsync(id); return vars[id]; };
// A component variable by name; a Button tone variable as the component variables it aliases in any mode.
const resolve = async (id, out) => {
  const v = await getVar(id);
  if (!v) return;
  const col = cols[v.variableCollectionId];
  if (col === 'Hirobius/Component') { out.add(v.name); return; }
  if (col !== 'Button tone') return;
  for (const val of Object.values(v.valuesByMode)) {
    if (val && val.type === 'VARIABLE_ALIAS') {
      const t = await getVar(val.id);
      if (t && cols[t.variableCollectionId] === 'Hirobius/Component') out.add(t.name);
    }
  }
};
const aliases = (o, acc) => {
  if (!o || typeof o !== 'object') return acc;
  if (o.type === 'VARIABLE_ALIAS' && o.id) { acc.push(o.id); return acc; }
  for (const x of Array.isArray(o) ? o : Object.values(o)) aliases(x, acc);
  return acc;
};
const bindings = {};
for (const id of IDS) {
  const node = await figma.getNodeByIdAsync(id);
  if (!node) { bindings[id] = { name: null, variables: [] }; continue; }
  const found = new Set();
  const nodes = [node].concat('findAll' in node ? node.findAll(() => true) : []);
  for (const n of nodes) {
    const ids = aliases(n.boundVariables || {}, []);
    for (const vid of ids) await resolve(vid, found);
  }
  bindings[id] = { name: node.name, variables: [...found].sort() };
}
const out = stable(bindings);
return { bindings: out, checksum: hdsChecksum(JSON.stringify(out)) };
`;
  if (script.length > SCRIPT_MAX_CHARS)
    throw new Error(`use_figma script is ${script.length} chars, over ${SCRIPT_MAX_CHARS}.`);
  return script;
}

/** Verify what use_figma returned and give the committed-file form of it. */
export function ingestBindings(result) {
  if (!result || !result.bindings || !result.checksum) throw new Error('Not a bindings result.');
  const bindings = stable(result.bindings);
  const got = hdsChecksum(JSON.stringify(bindings));
  if (got !== result.checksum)
    throw new Error(`Checksum mismatch (${got} != ${result.checksum}): save the result unedited.`);
  return { checksum: result.checksum, bindings };
}

/** One row per component token of a targeted group, sorted by id. */
export function compareBindings(codeResults, bindings, targets) {
  const byGroup = Object.fromEntries(targets.map((t) => [t.group, t.nodeIds]));
  const rows = [];
  for (const r of codeResults) {
    const ids = byGroup[r.group];
    if (!ids) continue;
    const variable = r.id.replaceAll('.', '/');
    const snapped = ids.filter((i) => bindings[i]);
    let status;
    if (snapped.length < ids.length) status = 'not-snapshotted';
    else {
      const figma = snapped.some((i) => bindings[i].variables.includes(variable));
      const code = r.class !== 'UNUSED';
      status = code && figma ? 'both' : code ? 'code-only' : figma ? 'figma-only' : 'neither';
    }
    rows.push({ id: r.id, variable, code: r.class, status });
  }
  return rows.sort((a, b) => a.id.localeCompare(b.id));
}

function codeResults(root) {
  const out = execFileSync(
    process.execPath,
    [join(root, 'scripts/check-component-token-binding.mjs'), '--json', '--root', root],
    { encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 },
  );
  return JSON.parse(out).results;
}

export function run(argv, { log = console.log } = {}) {
  const arg = (f) => {
    const i = argv.indexOf(f);
    return i === -1 ? null : argv[i + 1];
  };
  const root = arg('--root') ? resolve(arg('--root')) : REPO;
  if (argv.includes('--emit-script')) {
    const p = join(root, 'figma/push/use-figma/bindings-snapshot.js');
    mkdirSync(dirname(p), { recursive: true });
    const s = buildBindingsScript({ root });
    writeFileSync(p, s);
    log(`wrote ${p} (${s.length} chars)`);
    return 0;
  }
  if (arg('--ingest')) {
    const res = ingestBindings(readJson(resolve(arg('--ingest'))));
    writeFileSync(join(root, BINDINGS), JSON.stringify(res, null, 2) + '\n');
    log(`wrote ${BINDINGS} (${res.checksum})`);
    return 0;
  }
  const bPath = join(root, BINDINGS);
  const bindings = existsSync(bPath) ? readJson(bPath).bindings : {};
  const rows = compareBindings(codeResults(root), bindings, bindingTargets({ root }));
  if (argv.includes('--json')) {
    log(JSON.stringify(rows, null, 2));
    return 0;
  }
  const counts = {};
  for (const r of rows) counts[r.status] = (counts[r.status] || 0) + 1;
  for (const r of rows.filter((x) => x.status !== 'both' && x.status !== 'neither'))
    log(`${r.status.padEnd(16)} ${r.id.padEnd(40)} code ${r.code}`);
  log(
    `check-figma-bindings (report): ${rows.length} tokens · ` +
      Object.entries(counts)
        .map(([k, v]) => `${k} ${v}`)
        .join(' · '),
  );
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = run(process.argv.slice(2));
}
