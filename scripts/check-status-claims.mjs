#!/usr/bin/env node
/** @internal — not part of @hirobius/design-system public API surface. */
/**
 * check-status-claims — re-derives the asserted integers in root status.json
 * that already have a derivable source, so a hand-typed number can be caught
 * the way hds#285 was: `status.json` claimed "56 STORIES ALREADY HAVE play()
 * FUNCTIONS" from a naive `grep play:` that actually matched `display:` in
 * inline styles. The true count was 0, and nothing checked it.
 *
 * This does not parse status.json's prose (regex-matching free text is
 * exactly the kind of check that rots silently). Instead it writes a small
 * generated witness artifact, docs/guardrails/status-claims.json, holding the
 * counts status.json is allowed to assert without re-deriving them itself.
 * Anyone editing status.json's numeric claims should read this file first;
 * `--check` fails when the recorded witness has drifted from live reality,
 * which is the same trust-nothing-recorded pattern as check-sync-map.mjs and
 * figma:staging-inventory --check.
 *
 *   node scripts/check-status-claims.mjs             # print the derived counts
 *   node scripts/check-status-claims.mjs --write      # (re)write the witness file
 *   node scripts/check-status-claims.mjs --check      # exit 1 on drift
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { findStoryFiles } from './lib/story-link.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'docs/guardrails/status-claims.json');

const argv = process.argv.slice(2);
const CHECK = argv.includes('--check');
const WRITE = argv.includes('--write') || (!CHECK && !argv.includes('--json'));
const AS_JSON = argv.includes('--json');

// The exact bug from hds#285: a naive `grep play:` matches `display:` inside
// inline styles. Only count a real Storybook `play` story field.
const PLAY_FIELD_RE = /(^|[^a-zA-Z])play\s*:/;

function countPlayFunctions() {
  const files = findStoryFiles(ROOT);
  let count = 0;
  for (const file of files) {
    const src = readFileSync(path.join(ROOT, file), 'utf8');
    if (PLAY_FIELD_RE.test(src)) count += 1;
  }
  return count;
}

function derive() {
  return {
    storiesWithPlayFunction: countPlayFunctions(),
  };
}

function main() {
  const derived = derive();

  if (AS_JSON) {
    process.stdout.write(`${JSON.stringify(derived, null, 2)}\n`);
    return;
  }

  if (CHECK) {
    if (!existsSync(OUT)) {
      console.error(`✗ ${path.relative(ROOT, OUT)} does not exist — run with --write first.`);
      process.exitCode = 1;
      return;
    }
    const recorded = JSON.parse(readFileSync(OUT, 'utf8'));
    const driftKeys = Object.keys(derived).filter((k) => recorded[k] !== derived[k]);
    if (driftKeys.length > 0) {
      console.error('✗ status.json claim witness has drifted from live reality:');
      for (const k of driftKeys) {
        console.error(`  ${k}: recorded ${recorded[k]}, actual ${derived[k]}`);
      }
      console.error(
        `  Update the claim in status.json, then run: node scripts/check-status-claims.mjs --write`,
      );
      process.exitCode = 1;
      return;
    }
    console.log(`✓ status claim witness matches reality (${JSON.stringify(derived)})`);
    return;
  }

  if (WRITE) {
    writeFileSync(
      OUT,
      `${JSON.stringify(
        {
          $comment:
            'Generated by scripts/check-status-claims.mjs. Re-derived counts that ' +
            'status.json is allowed to assert without hand-typing them (hds#285). ' +
            'Run --check to catch drift; run --write after fixing a claim.',
          ...derived,
        },
        null,
        2,
      )}\n`,
    );
    console.log(`Wrote ${path.relative(ROOT, OUT)}: ${JSON.stringify(derived)}`);
    return;
  }

  console.log(JSON.stringify(derived, null, 2));
}

main();
