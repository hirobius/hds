#!/usr/bin/env node
/** @internal — not part of @hirobius/design-system public API surface. */
/**
 * generate-code-connect.mjs
 *
 * Writes Figma Code Connect v2 parserless templates (`<module>.figma.ts`) for
 * every component in figma/code-connect.json. The Figma side (property names,
 * options, and how each maps onto a prop) comes from the registry. The code side
 * (props, required-ness, cva variants + defaultVariants) is read from source
 * through the TypeScript checker. The node URL comes from
 * public/hds-manifest.json `figmaUrl`, which is fed by the component JSDoc tag
 * `@figma <node-url>`. A component without one gets a placeholder `// url=`
 * and is reported as unmapped.
 *
 * No network, no token, no publish. Publishing (`figma connect publish`)
 * needs a Figma Organization plan and is intentionally not wired here.
 *
 * Run:   pnpm figma:connect:generate           write / refresh templates
 *        pnpm figma:connect:generate --check   exit 1 if committed templates drift
 *        ... --root <dir>                      against a copy of the tree (tests)
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createCodeModel } from './lib/component-code-model.mjs';
import { rootFromArgv, runGenerator } from './lib/generated-check.mjs';
import { formatCommitted } from './lib/write-generated.mjs';
import {
  REGISTRY_PATH,
  buildTemplateSource,
  classifyFigmaUrl,
  templatePathFor,
  validateTemplateEntry,
} from './lib/code-connect-template.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
// Honours FIXTURE_DIR for the same reason check-code-connect.mjs does: the
// gate's fixture holds generated templates, and they have to be producible by
// the real generator or the fixture is hand-written fiction.
const DEFAULT_ROOT = process.env.FIXTURE_DIR
  ? path.resolve(process.env.FIXTURE_DIR)
  : path.join(__dirname, '..');
export const GENERATED_MARKER = '// GENERATED by scripts/generate-code-connect.mjs';

export function loadCodeConnectInputs(root = DEFAULT_ROOT) {
  const readJson = (file) => JSON.parse(fs.readFileSync(path.join(root, file), 'utf8'));
  return { registry: readJson(REGISTRY_PATH), manifest: readJson('public/hds-manifest.json') };
}

export function registrySourceFiles(registry) {
  return Object.values(registry.templates ?? {}).map((entry) => entry.source);
}

function figmaUrlFor(manifest, name) {
  return (
    manifest?.componentSpecs?.[name]?.figmaUrl ?? manifest?.utilities?.[name]?.figmaUrl ?? null
  );
}

/**
 * @returns {Promise<{ files: { name: string, path: string, content: string, status: 'mapped'|'unmapped' }[], errors: string[] }>}
 */
export async function generateTemplates({ root = DEFAULT_ROOT, registry, manifest, codeModel }) {
  const files = [];
  const errors = [];
  const model = codeModel ?? createCodeModel({ root, files: registrySourceFiles(registry) });

  for (const [name, entry] of Object.entries(registry.templates ?? {})) {
    const exportName = entry.export ?? name;
    const code = model.component(entry.source, exportName);
    const entryErrors = validateTemplateEntry(name, entry, code);
    const figmaUrl = figmaUrlFor(manifest, name);
    const status = classifyFigmaUrl(figmaUrl);
    if (status === 'invalid') {
      entryErrors.push(
        `${name}: manifest figmaUrl "${figmaUrl}" is not a Figma node URL (https://www.figma.com/design/<file>/<name>?node-id=<x>-<y>)`,
      );
    }
    if (entryErrors.length > 0) {
      errors.push(...entryErrors);
      continue;
    }

    const relativePath = templatePathFor(entry);
    const source = buildTemplateSource({
      name,
      exportName,
      entry,
      code,
      figmaUrl,
      importFrom: registry.importFrom,
    });
    // This repo's Prettier config whatever the root, so a fixture or a copy of
    // the tree formats exactly like the committed templates.
    const content = await formatCommitted(relativePath, source);
    files.push({ name, path: relativePath, content, status });
  }

  return { files, errors };
}

/** Generated templates currently on disk (identified by the GENERATED marker). */
export function findGeneratedTemplates(root = DEFAULT_ROOT, dir = 'src/app/components') {
  const absoluteDir = path.join(root, dir);
  if (!fs.existsSync(absoluteDir)) return [];
  return fs
    .readdirSync(absoluteDir)
    .filter((file) => file.endsWith('.figma.ts'))
    .map((file) => `${dir}/${file}`)
    .filter((file) => fs.readFileSync(path.join(root, file), 'utf8').includes(GENERATED_MARKER));
}

/** Compare generated output with the working tree. */
export function diffAgainstDisk(root, files) {
  const drift = [];
  for (const file of files) {
    const absolute = path.join(root, file.path);
    const onDisk = fs.existsSync(absolute)
      ? fs.readFileSync(absolute, 'utf8').replace(/\r\n/g, '\n')
      : null;
    if (onDisk === null) drift.push(`${file.path}: missing`);
    else if (onDisk !== file.content) drift.push(`${file.path}: differs from generator output`);
  }
  const expected = new Set(files.map((file) => file.path));
  for (const stale of findGeneratedTemplates(root)) {
    if (!expected.has(stale)) drift.push(`${stale}: generated template with no registry entry`);
  }
  return drift;
}

async function main() {
  const root = rootFromArgv(DEFAULT_ROOT);
  const { registry, manifest } = loadCodeConnectInputs(root);
  const { files, errors } = await generateTemplates({ root, registry, manifest });

  if (errors.length > 0) {
    for (const message of errors) console.error(`  error ${message}`);
    console.error(
      `✗ generate-code-connect — ${errors.length} registry error(s) in ${REGISTRY_PATH}`,
    );
    process.exit(1);
  }

  // One template per registry entry; a generated template whose entry went
  // away must not exist (null), so a write removes it and --check names it.
  const outputs = Object.fromEntries(files.map((file) => [file.path, file.content]));
  for (const stale of findGeneratedTemplates(root)) {
    if (!(stale in outputs)) outputs[stale] = null;
  }
  const result = await runGenerator({
    root,
    outputs,
    label: 'generate-code-connect',
    fix: 'pnpm figma:connect:generate',
  });
  if (!result.check) {
    const unmapped = files.filter((file) => file.status !== 'mapped').map((file) => file.name);
    console.log(
      `  ${files.length} template(s); ${files.length - unmapped.length} mapped, ${unmapped.length} unmapped${unmapped.length ? ` (${unmapped.join(', ')})` : ''}`,
    );
  }
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))
) {
  await main();
}
